"""Крипта, блок 6. Институциональные двери: через что в крипту приходят большие деньги — спотовые ETF, фьючерсы CME
(и базисная сделка), компании, которые копят биткоин. Какая часть этих денег — настоящий спрос, а какая — арбитраж."""
import pandas as pd
import streamlit as st

from core import crypto, learn, ui
from core.charts import dual_axis_chart, line_chart
from core.learn import Example
from core.transforms import cut

PERIODS = {"2 года": 2, "5 лет": 5, "Вся история": None}


@st.cache_data(ttl=12 * 3600, show_spinner=False)
def treasuries():
    return crypto.treasuries()


@st.cache_data(ttl=12 * 3600, show_spinner=False)
def strategy_kpi():
    return crypto.strategy_kpi()


# ---------- данные ----------
COST = 0.75  # издержки базисной сделки сверх векселей, п.п.: фондирование по SOFR + спред, маржа CME, комиссия ETF
btc = ui.load("BTC-USD").dropna()
price = float(btc.iloc[-1])
bas = crypto.basis(ui.load)
bill = ui.load("DGS3MO").dropna()
am, lf = ui.load("COT_BTC_AM").dropna(), ui.load("COT_BTC_LEV").dropna()
edge = float(bas.iloc[-1] - bill.iloc[-1] - COST)  # доход сделки сверх безубыточности
lf_8w = float(lf.iloc[-1] - lf.iloc[-9]) if len(lf) > 9 else 0.0  # плюс — шорт фондов с плечом сокращается
mb, mc = crypto.pair_beta(ui.load, "MSTR")
tr = treasuries()
kpi = strategy_kpi()
strategy = next((x for x in (tr or {}).get("companies", []) if x["name"] == "Strategy"), None)
m_cap, m_ev = crypto.mnav(kpi, strategy["total_holdings"] * price) if kpi and strategy else (None, None)
lf_peak = float(lf["2024":].min())

# ---------- шапка ----------
learn.crypto_header(crypto.BY_NUM[2], len(crypto.BLOCKS),
                    "Крупные фонды не покупают монеты на криптобиржах: им нужны регулируемые обёртки. Таких дверей "
                    "три — спотовые ETF, фьючерсы на чикагской бирже CME и акции компаний, которые копят биткоин. "
                    "Через каждую дверь идёт и настоящий спрос, и арбитраж, который цену не толкает.")

learn.takeaway("Двери: базисная сделка " + ("выгодна — часть притока в ETF арбитраж" if edge > 0.5 else
                                              "убыточна — арбитражный приток иссякает" if edge < -0.5 else
                                              "на грани безубыточности")
               + (f"; Strategy стоит {m_ev:.2f} от своих биткоинов — "
                  + ("премия есть, она может докупать монеты" if m_ev > 1.1 else "премии почти нет")
                  if m_ev else "") + ".", "warn" if (m_ev and m_ev < 1) or edge < -0.5 else "neutral")

c = st.columns(3)
c[0].metric("Базис CME", f"{bas.iloc[-1]:.1f}%", f"годовых · векселя {bill.iloc[-1]:.1f}%", delta_color="off",
            border=True, help="Насколько фьючерс CME дороже спота в пересчёте на год. Сглаженная оценка: закрытия CME "
                              f"и спота разнесены по времени. Безубыточность сделки ≈ векселя + {COST} п.п.")
c[1].metric("Фонды с плечом на CME", f"{lf.iloc[-1]:+.0f}%", f"{lf_8w:+.0f} п.п. за 8 недель · максимум шорта {lf_peak:.0f}%",
            delta_color="off", border=True, help="Хедж-фонды и трендовые фонды (CTA). Их шорт — в основном вторая "
                                                 "нога базисной сделки, а не ставка на падение.")
c[2].metric("Strategy: стоимость к биткоинам", f"{m_ev:.2f}" if m_ev else "нет данных",
            f"mNAV с долгом · по капитализации {m_cap:.2f}" if m_cap else "mNAV", delta_color="off", border=True,
            help="(Капитализация + долг + привилегированные акции − деньги) / стоимость биткоинов компании — так "
                 "mNAV считает сама Strategy. 1 — без премии. Данные сайта компании и Yahoo, оценка.")

years = PERIODS[st.segmented_control("Период графиков", list(PERIODS), default="5 лет", key="period") or "5 лет"]

# ---------- 1. базисная сделка ----------
st.header("1. Базисная сделка: приток, который не толкает цену")
st.markdown("Фьючерс на CME обычно дороже спота: покупатели с плечом готовы доплатить. Хедж-фонд покупает ETF и "
            "одновременно продаёт фьючерс — и спокойно забирает разницу (базис), не рискуя ценой биткоина. В "
            "статистике это выглядит как приток в ETF, но сам хедж-фонд на цену не ставит: направленный спрос несёт "
            "тот, кто купил у него фьючерс с плечом.")
learn.tags("совпадающий", "проверен на истории")
st.plotly_chart(line_chart({"Базис CME, % годовых": cut(bas, years), "Казначейские векселя 3 мес., %": cut(bill, years)},
                           units="%", height=300), width="stretch")
st.caption(f"Сделка выгодна, когда базис выше векселей примерно на {COST} п.п. (фондирование, маржа, комиссия ETF). "
           "Сворачивают её обычно тихо: у экспирации не переходят в новый контракт и гасят паи ETF.")
with st.expander("🔬 Подробнее для продвинутых: кто стоит за базисной сделкой (CFTC)"):
    st.plotly_chart(line_chart({"Управляющие активами": cut(am, years), "Фонды с плечом": cut(lf, years)},
                               units="%", zero_line=True, height=300), width="stretch")
    st.caption("Чистые позиции на CME по еженедельному отчёту CFTC, % открытого интереса. Глубокий шорт фондов с "
               "плечом при лонге управляющих — признак базисной сделки.")

with learn.how_it_works():
    st.markdown("""
- **Почему фьючерс дороже.** Купить биткоин с плечом через фьючерс удобнее, чем занимать доллары. Покупатели
  доплачивают за это — как процент по кредиту. Чем сильнее жадность, тем выше базис.
- **Кто забирает разницу.** Фонды с дешёвым финансированием покупают монету (или ETF) и продают фьючерс. К
  экспирации цены сходятся, базис — их доход. Это та же сделка, что гасит фандинг в бессрочных фьючерсах (блок 1).
- **Почему это важно трейдеру.** Новость «в ETF пришёл миллиард» не значит, что кто-то поверил в биткоин на
  миллиард. Часть притока — арбитраж, и он уйдёт так же быстро, когда базис упадёт ниже ставок.
- **Ограничение оценки.** Ряд фьючерса — ближний контракт Yahoo, закрытие CME и спота в разное время, поэтому
  базис здесь — сглаженная оценка, а не точная цифра.
""")

# ---------- 2. ETF ----------
st.header("2. Спотовые ETF")
st.markdown("С января 2024 года в США торгуются биржевые фонды, которые держат настоящие биткоины. Покупка паёв на "
            "бирже — обмен между инвесторами. Монеты фонд покупает, только когда спрос на паи превышает "
            "предложение: тогда крупные банки-посредники (авторизованные участники) создают новые паи, и фонд "
            "докупает биткоин — обычно на следующий день. Это и есть «приток». ETF — главная дверь для "
            "пенсионных фондов, советников и брокерских счетов, куда крипту раньше было не положить.")
learn.tags("запаздывающий", "проверен на истории")
flow = ui.load("ETF_FLOW_BTC")
ev = crypto.etf_vs_btc(ui.load)
f20 = flow.rolling(20).sum()
c = st.columns(3)
c[0].metric("Приток за 20 торговых дней", f"${f20.iloc[-1] / 1000:+.1f} млрд",
            f"выше, чем в {(f20 < f20.iloc[-1]).mean() * 100:.0f}% истории", delta_color="off", border=True)
c[1].metric("Всего с запуска", f"${flow.sum() / 1000:.0f} млрд", "чистый приток", delta_color="off", border=True)
c[2].metric("Последний день", f"${flow.iloc[-1]:+.0f} млн", f"{flow.index[-1]:%d.%m}", delta_color="off", border=True)
st.plotly_chart(dual_axis_chart(("Приток за 20 дней", f20 / 1000, "млрд $"), ("Биткоин", btc[f20.index[0]:], "$"),
                                height=300), width="stretch")
st.markdown(f"**Проверка на истории** ({ev['n']} недель с запуска): связь притока с ценой в ту же неделю "
            f"{ev['same']:+.2f}, с ценой прошлой недели {ev['after']:+.2f}, со следующей неделей {ev['before']:+.2f}. "
            f"Потоки идут **вместе с ценой и вслед за ней**: рост приводит в ETF новых покупателей, падение их "
            f"выгоняет. Предсказать цену по потокам нельзя — это та же петля «цена ↑ → приток → цена ↑», что на карте.")
st.caption("Данные Farside через сервис trade-news; свежий день дозаполняется на следующее утро.")

# ---------- 3. компании ----------
st.header("3. Компании-казначейства")
st.markdown(f"Некоторые компании копят биткоин на балансе. Крупнейшая — Strategy (бывшая MicroStrategy): она "
            f"выпускает акции и облигации и на эти деньги покупает монеты. Её акция ведёт себя как биткоин с "
            f"плечом: с 2021 года на 1% движения биткоина за неделю она в среднем сдвигается на {mb:.1f}% "
            f"(корреляция {mc:+.2f}); в разные годы бета заметно менялась.")
learn.tags("совпадающий", "проверен на истории")
if tr:
    rows = [(x["name"], x["total_holdings"], x["percentage_of_total_supply"]) for x in tr["companies"][:10]]
    c = st.columns(3)
    c[0].metric("У всех публичных компаний", f"{tr['total_holdings'] / 1e6:.2f} млн BTC", border=True)
    c[1].metric("Доля от всех биткоинов", f"{sum(x['percentage_of_total_supply'] for x in tr['companies']):.1f}%", border=True)
    c[2].metric("У Strategy", f"{strategy['total_holdings']:,.0f} BTC".replace(",", " ") if strategy else "—",
                border=True)
    st.dataframe(pd.DataFrame(rows, columns=["Компания", "BTC", "% всех биткоинов"])
                 .style.format({"BTC": "{:,.0f}", "% всех биткоинов": "{:.2f}"}), hide_index=True, width="stretch")
    st.caption("Снимок CoinGecko на сегодня; список неполный — мелкие компании в него не попадают. История запасов "
               "пока не копится.")
else:
    st.warning("CoinGecko не ответил — данных о запасах компаний нет.")

with learn.how_it_works("Петля компании-казначейства"):
    st.markdown("""
- **На росте.** Биткоин дорожает → акция компании растёт ещё сильнее, рынок платит **премию** к стоимости её
  биткоинов (mNAV больше 1) → компания выпускает новые акции дороже, чем стоят монеты на одну акцию → покупает
  биткоин → цена растёт. Каждый новый акционер «покупает» биткоин дороже рынка, и это работает, пока премия есть.
- **Топливо не только акции.** Strategy выпускает конвертируемые облигации (низкие купоны) и привилегированные
  акции с высокими дивидендами — их можно продавать и без премии. Главная денежная нагрузка компании — именно
  дивиденды по привилегированным акциям.
- **На спаде петля останавливается.** Премия исчезает (mNAV около 1 или ниже) → выпуск обычных акций больше не
  выгоден → покупки замедляются. Если денег на дивиденды и проценты не хватит, компании придётся продавать акции
  ниже стоимости биткоинов или сами монеты.
- **Что проверено, а что нет.** Связь акции с биткоином (бета) видна на истории. А насколько покупки компаний
  двигают цену биткоина — спорно: история короткая, точных данных мало.
""")


# ---------- примеры ----------
def show_window(start: str, end: str, text: str) -> None:
    s = btc[start:end]
    st.metric("Биткоин за период", f"{(s.iloc[-1] / btc[:start].iloc[-1] - 1) * 100:+.0f}%", border=True)
    st.plotly_chart(line_chart({"Биткоин": s}, units="$", height=260), width="stretch")
    st.markdown(text)


def basis_2024():
    w = bas["2023-10":"2025-03"]
    c = st.columns(2)
    c[0].metric("Базис, максимум", f"{w.max():.1f}%", f"годовых, {w.idxmax():%m.%Y}", delta_color="off", border=True)
    c[1].metric("Шорт фондов с плечом, максимум", f"{lf['2023-10':'2025-03'].min():.0f}%", "откр. интереса",
                delta_color="off", border=True)
    st.plotly_chart(dual_axis_chart(("Базис CME", w, "% годовых"), ("Фонды с плечом", lf["2023-10":"2025-03"], "%"),
                                    invert_right=True, height=280), width="stretch")
    st.markdown("После запуска ETF и на росте конца 2024 года жадность подняла базис намного выше ставок по векселям. "
                "Хедж-фонды набрали рекордный шорт на CME — вторую ногу сделки «купить ETF, продать фьючерс». Правая "
                "ось перевёрнута: чем выше линия, тем больше шорт.")


def strategy_ex():
    m = ui.load("MSTR").dropna()["2024":]
    st.plotly_chart(dual_axis_chart(("Strategy", m, "$ за акцию"), ("Биткоин", btc["2024":], "$"), height=280),
                    width="stretch")
    now = (f"Сейчас компания стоит {m_ev:.2f} от своих биткоинов с учётом долга — "
           + ("премия есть, петля может работать." if m_ev > 1.1 else
              "премии почти нет, петля на обыкновенных акциях буксует.")) if m_ev else ""
    st.markdown(f"Акция Strategy усиливает движения биткоина в обе стороны (бета с 2021 года {mb:.1f}). На росте "
                f"рынок платил за неё премию к биткоинам на балансе, и компания на выпуске акций докупала монеты. "
                f"Когда премия сжимается, топливо петли кончается. {now}")


learn.examples([
    Example("2024: базисная сделка на пике", basis_2024),
    Example("Январь 2024: ETF запустили — цена упала", lambda: show_window(
        "2024-01-10", "2024-01-23",
        "11 января 2024 года запустились спотовые ETF — событие, которого рынок ждал годами. Цена падала ещё две "
        "недели: на новостях продают те, кто купил на ожиданиях. А старый фонд GBTC годами был закрытым трастом "
        "без погашения и торговался с дисконтом; став ETF, он дал выход по полной стоимости — деньги забрали "
        "арбитражёры и банкроты вроде FTX, а остальные уходили в фонды с комиссией в разы ниже. «Покупай на слухах, продавай на фактах»."), normal=False),
    Example("Strategy — биткоин с плечом", strategy_ex, normal=False),
], key="doors")

