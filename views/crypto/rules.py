"""Крипта, блок 5. Регулирование и шоки: как биткоин реагирует на решения регуляторов, запреты и аварии — и что
из этого запоминается рынку надолго."""
import pandas as pd
import streamlit as st

from core import crypto, learn, ui
from core.charts import line_chart
from core.learn import Example

KINDS = {"рег+": "Правила смягчают", "рег−": "Правила ужесточают", "шок": "Аварии и паника"}

# ---------- данные ----------
btc = ui.load("BTC-USD").dropna()
ev = crypto.event_study(ui.load)
by = ev.groupby("Вид").agg(n=("Событие", "size"), d1=("За 2 дня, %", "mean"), z=("В обычных колебаниях", "mean"),
                           d30=("За месяц, %", "mean"), up30=("За месяц, %", lambda s: (s > 0).mean() * 100))

# ---------- шапка ----------
learn.crypto_header(crypto.BY_NUM[3], len(crypto.BLOCKS),
                    "У крипты нет центрального банка и нет прибыли, зато есть правила: что разрешено, кому, на каких "
                    "биржах. Решения регуляторов открывают и закрывают двери для денег (блок 6), а аварии — "
                    "крахи бирж и стейблкоинов — бьют по доверию. Блок проверяет на истории, какие события "
                    "двигают цену и надолго ли.")

learn.takeaway(f"Регуляторные новости рынок отыгрывает заранее: в день события смягчение правил даёт в среднем "
               f"{by.loc['рег+', 'd1']:+.1f}%, меньше обычных колебаний. Запреты пугают ненадолго — через месяц цена "
               f"выше в {by.loc['рег−', 'up30']:.0f}% случаев. Сильнее всего бьют аварии внутри крипты: "
               f"{by.loc['шок', 'd1']:+.0f}% за 2 дня, и через месяц цена ниже в {100 - by.loc['шок', 'up30']:.0f}% "
               f"случаев.", "neutral")

c = st.columns(3)
for col, (k, name) in zip(c, KINDS.items()):
    col.metric(name, f"{by.loc[k, 'd1']:+.1f}% за 2 дня", f"через месяц {by.loc[k, 'd30']:+.0f}% · {by.loc[k, 'n']} "
                                                          f"событий", delta_color="off", border=True)

# ---------- 1. таблица событий ----------
st.header("1. Как рынок встречал события")
st.markdown("Ключевые события с 2017 года и изменение цены биткоина после них. «В обычных колебаниях» — во сколько раз "
            "движение за 2 дня больше типичного для того времени: около 1 — обычный день, 3 и больше — редкое "
            "потрясение.")
learn.tags("совпадающий", "спорный")
show = ev.assign(Дата=ev["Дата"].dt.strftime("%d.%m.%Y"), Вид=ev["Вид"].map(KINDS))
st.dataframe(show.style.format({"За 2 дня, %": "{:+.1f}", "В обычных колебаниях": "{:+.1f}", "За неделю, %": "{:+.1f}",
                                "За месяц, %": "{:+.1f}"}, na_rep="—"), hide_index=True, width="stretch")
st.caption("Изменение от закрытия накануне события. Событий мало, и в месяц после них происходит много другого — это "
           "картина, а не строгий закон, отсюда метка «спорный». Список событий составлен вручную.")

pick = st.selectbox("Посмотреть событие на графике", ev["Событие"].tolist(), key="rules_pick")
row = ev[ev["Событие"] == pick].iloc[0]
d = row["Дата"]
w = btc[d - pd.Timedelta(days=30):d + pd.Timedelta(days=45)]
st.plotly_chart(line_chart({"Биткоин": w / btc[:d - pd.Timedelta(days=1)].iloc[-1] * 100}, height=260),
                width="stretch")
st.caption(f"{row['Дата']:%d.%m.%Y} — {next(e[3] for e in crypto.EVENTS if e[1] == pick)} Цена накануне = 100.")

with learn.how_it_works():
    st.markdown("""
- **«Покупай на слухах, продавай на фактах».** Если событие ждали, цена растёт заранее, а в день решения часть
  покупателей фиксирует прибыль. Поэтому заявка BlackRock на ETF двинула рынок сильнее, чем само одобрение.
- **Запреты одной страны не убивают глобальный рынок.** Майнеры и трейдеры переезжают, а продавцы под давлением
  быстро заканчиваются. Опаснее запреты, которые закрывают двери в крупнейших рынках денег — в США.
- **Аварии внутри крипты — самое опасное.** Крах биржи или стейблкоина уничтожает деньги и залог, запускает
  ликвидации (блок 1) и цепочки банкротств кредиторов. Это не «новость», а изъятие денег из системы — поэтому
  эффект держится неделями.
- **Как использовать.** Перед ожидаемым решением регулятора смотрите, сколько уже выросло: если много — после
  решения часто бывает откат. На авариях не спешите «ловить дно»: первые дни обычно не последние.
""")

