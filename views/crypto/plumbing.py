"""Крипта, блок 2. Биржи, стейблкоины и точки отказа: на каких долларах держится крипта, кто их выпускает и
зарабатывает на ставках ФРС, и что ломается — потеря привязки стейблкоина, банкротство биржи."""
import pandas as pd
import streamlit as st

from core import crypto, learn, ui
from core.charts import dual_axis_chart, line_chart
from core.learn import Example
from core.transforms import cut

NUM = 5
PERIODS = {"3 года": 3, "5 лет": 5, "Вся история": None}

# ---------- данные ----------
tot, usdt, usdc = ui.load("STABLE_TOTAL"), ui.load("STABLE_USDT"), ui.load("STABLE_USDC")
btc = ui.load("BTC-USD").dropna()
bill = ui.load("DGS3MO").dropna()
g90 = crypto.supply_growth(ui.load)
g_pct = float((g90["2019":] < g90.iloc[-1]).mean() * 100)
link = crypto.supply_vs_btc(ui.load)
share = float(usdt.iloc[-1] / tot.iloc[-1] * 100)
BILLS = 0.8  # доля резервов Tether в векселях, обратном репо и фондах денежного рынка — по его аттестациям, оценка
income = float(usdt.iloc[-1] * BILLS * bill.iloc[-1] / 100)

# ---------- шапка ----------
learn.crypto_header(crypto.BY_NUM[NUM], len(crypto.BLOCKS),
                    "Почти вся торговля криптой идёт не за настоящие доллары, а за **стейблкоины** — токены, которые "
                    "обещают стоить ровно $1. Блок идёт от самих денег (части 1–3) к местам, где они лежат и кто "
                    "может их остановить (части 4–5).")

head = ("Топливо прибывает: стейблкоинов становится заметно больше" if g_pct >= 70 else
        "Топливо почти не прибывает: стейблкоинов становится больше медленно" if g_pct <= 30 else
        "Топливо прибывает в обычном темпе")
learn.takeaway(f"{head} — {g90.iloc[-1]:+.1f}% за 90 дней. Рост стейблкоинов идёт вместе с рынком, а не заранее.",
               "neutral" if g_pct > 30 else "warn")

depeg_days = sum(int(crypto.depegs(ui.load, x)["Дней"].sum()) for x in ("USDT", "USDC", "DAI")
                 if len(crypto.depegs(ui.load, x)))
c = st.columns(3)
c[0].metric("1 · Стейблкоины в обращении", f"${tot.iloc[-1]:.0f} млрд", f"{g90.iloc[-1]:+.1f}% за 90 дней",
            delta_color="off", border=True, help="Все долларовые стейблкоины по данным DefiLlama.")
c[1].metric("2 · Дней ниже $0,99", f"{depeg_days}", "USDT, USDC, DAI с 2021 года", delta_color="off", border=True,
            help="По дневной цене DefiLlama. Внутри дня провалы глубже.")
c[2].metric("3 · Доход Tether на процентах", f"≈${income:.1f} млрд", f"в год при векселях {bill.iloc[-1]:.1f}%",
            delta_color="off", border=True, help=f"Грубая оценка: около {BILLS:.0%} резервов в векселях и похожих "
                                                 "бумагах × ставка 3-месячных векселей.")

years = PERIODS[st.segmented_control("Период графиков", list(PERIODS), default="5 лет", key="period") or "5 лет"]

# ---------- 1. доллары внутри крипты ----------
with learn.part_section(NUM, "money"):
    st.markdown("Выпускать и гасить стейблкоины напрямую у эмитента могут только проверенные крупные клиенты (у "
                "Tether — от $100 тыс.): они приносят доллары и получают токены, или наоборот. Все остальные покупают "
                "токены на бирже. Стейблкоины в обращении — деньги, уже заведённые в крипту и готовые к покупкам или "
                "к залогу под плечо.")
    st.plotly_chart(dual_axis_chart(("Стейблкоины", cut(tot, years), "млрд $"), ("Биткоин", cut(btc, years), "$"),
                                    height=300), width="stretch")
    st.markdown(f"**Доказательство** (непересекающиеся кварталы с 2019 года, {link['n']} шт.): связь роста "
                f"стейблкоинов и биткоина в том же квартале {link['same']:+.2f}, с биткоином следующего квартала "
                f"{link['lead']:+.2f}. Шум при такой выборке — до ±{crypto.noise(link['n']):.2f}.")
