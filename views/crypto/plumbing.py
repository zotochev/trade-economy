with learn.how_it_works("Почему это точка отказа"):
    st.markdown("""
- **Залог.** На биржах стейблкоины — главный залог под фьючерсы. Если залог дешевеет, позиции под ним
  ликвидируются, даже если трейдер угадал направление.
- **Банки эмитентов.** Резервы лежат в обычных банках. Банк рухнул — часть резервов заморожена, токен дешевеет
  (USDC и SVB, март 2023).
- **Алгоритмические стейблкоины.** Без долларовых резервов, привязка держится на вере и арбитраже. Когда вера
  уходит, они падают до нуля (UST, май 2022).
- **Заморозка.** Tether и Circle могут заморозить токены на любом адресе по запросу властей — и делают это
  (биржа Garantex, март 2025). Для пользователей под санкционным риском это главный риск стейблкоина.
- **Регулирование.** В ЕС по правилам MiCA с 2024 года USDT ограничен для пользователей из ЕС; в США GENIUS Act
  (2025) требует от эмитентов резервов 1:1 в деньгах и векселях.
""")

