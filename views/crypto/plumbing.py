# ---------- примеры ----------
def peg_window(coin: str, start: str, end: str, text: str) -> None:
    lo = ui.load(f"PEGLOW_{coin}")[start:end]  # минимум дня Yahoo: для этого эпизода он подтверждён
    b = btc[start:end]
    c = st.columns(2)
    c[0].metric(f"{coin}: минимум", f"${lo.min():.3f}", border=True)
    c[1].metric("Биткоин за период", f"{(b.iloc[-1] / b.iloc[0] - 1) * 100:+.0f}%", border=True)
    st.plotly_chart(dual_axis_chart((f"{coin}, минимум дня", lo, "$"), ("Биткоин", b, "$"), height=280),
                    width="stretch")
    st.markdown(text)


def supply_window(start: str, end: str, text: str) -> None:
    s, b = tot[start:end], btc[start:end]
    c = st.columns(2)
    c[0].metric("Стейблкоины", f"{(s.iloc[-1] / s.iloc[0] - 1) * 100:+.0f}%", border=True)
    c[1].metric("Биткоин", f"{(b.iloc[-1] / b.iloc[0] - 1) * 100:+.0f}%", border=True)
    st.plotly_chart(dual_axis_chart(("Стейблкоины", s, "млрд $"), ("Биткоин", b, "$"), height=280), width="stretch")
    st.markdown(text)


