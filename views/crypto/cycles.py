"""Крипта, блок 8. Циклы: четырёхлетний ритм биткоина — вершины после халвингов, медвежьи рынки примерно на год,
и как этот ритм слабеет по мере того, как рынок взрослеет."""
import pandas as pd
import streamlit as st

from core import crypto, learn, ui
from core.charts import grouped_bars, line_chart
from core.learn import Example

# ---------- данные ----------
o = crypto.onchain(ui.load)
p = o["price"]["2011":]
dd = (p / p.cummax() - 1) * 100
bears = crypto.bear_markets(ui.load)
hp = crypto.halving_peaks(ui.load)
# медвежьи рынки после вершин циклов (вершина после халвинга), уже закончившиеся
big = bears[bears["Вершина"].isin(hp["Вершина"]) & bears["Дней от дна до новой вершины"].notna()]
vol = crypto.yearly_vol(ui.load)
ath_day = p.idxmax()
since_ath = (p.index[-1] - ath_day).days
cur = bears.iloc[-1]
open_bear = pd.isna(cur["Дней от дна до новой вершины"]) and pd.Timestamp(cur["Вершина"]) == ath_day.normalize()
days_to_bottom = big["Дней до дна"]

# ---------- шапка ----------
learn.crypto_header(crypto.BY_NUM[8], len(crypto.BLOCKS),
                    "У биткоина есть ритм: примерно раз в четыре года — бурный рост, вершина, падение на год и "
                    "больше на 75–90%, затем долгое восстановление. Ритм совпадает с халвингами, но держится и на "
                    "людях: страх и жадность, плечо (блок 1), держатели в прибыли (блок 7), мировые деньги (блок 4). "
                    "Циклов было всего три-четыре, поэтому это ориентир, а не расписание.")

learn.takeaway(f"Последняя вершина — {ath_day:%d.%m.%Y}, цена сейчас на {abs(dd.iloc[-1]):.0f}% ниже. В прошлых "
               f"циклах дно приходило через {days_to_bottom.min()}–{days_to_bottom.max()} дней после вершины"
               + ("; этот цикл пока мельче прошлых — рынок взрослеет." if open_bear else "."), "neutral")

c = st.columns(3)
c[0].metric("От вершины", f"{dd.iloc[-1]:.0f}%", f"вершина {ath_day:%d.%m.%Y}", delta_color="off", border=True)
c[1].metric("Дней после вершины", f"{since_ath}", f"прошлые медвежьи рынки: {days_to_bottom.min()}–"
                                                   f"{days_to_bottom.max()} дн. до дна", delta_color="off", border=True)
c[2].metric("Вершина после халвинга", f"{hp['Дней после халвинга'].iloc[-1]} дн.",
            f"прошлые: {hp['Дней после халвинга'].iloc[:-1].min()}–{hp['Дней после халвинга'].iloc[:-1].max()} дн.",
            delta_color="off", border=True)

# ---------- 1. ритм ----------
st.header("1. Четыре года: рост, вершина, падение, восстановление")
learn.tags("совпадающий", "спорный")
st.plotly_chart(line_chart({"Падение от максимума": dd}, units="%", height=300), width="stretch")
st.caption("Насколько цена ниже предыдущего максимума, %. Ноль — новый рекорд.")
show_all = st.toggle("Показать все падения глубже 50%", key="cyc_all")
view = bears if show_all else bears[bears["Вершина"].isin(hp["Вершина"])]
view = view.assign(Дно=[f"{d:%d.%m.%Y}" + (" (пока)" if pd.isna(r) else "")
                        for d, r in zip(view["Дно"], view["Дней от дна до новой вершины"])])
st.dataframe(view.style.format({"Цена на вершине, $": "{:,.0f}", "Глубина, %": "{:.0f}",
                                "Дней от дна до новой вершины": "{:.0f}"}, na_rep="ещё нет"),
             hide_index=True, width="stretch")
st.caption("Медвежьи рынки после вершин циклов — по одному на цикл. Падения на 50–70% бывали и посреди бычьего рынка "
           "(весна 2013 и 2021 годов) — их показывает переключатель. «Пока» — дно ещё не подтверждено новым рекордом.")

with learn.how_it_works():
    st.markdown("""
- **Рост.** Цена растёт → в прибыли всё больше держателей, в новостях — рекорды → приходят новые покупатели и
  берут плечо → рост ускоряется. Каждая петля с карты работает на рост.
- **Вершина.** Держатели в огромной прибыли продают (MVRV выше 3, блок 7), плечо перегрето (блок 1), новые деньги
  кончаются. Хватает одного удара — и петли разворачиваются.
- **Падение.** Ликвидации, банкротства бирж и кредиторов (Mt. Gox в 2014 году; Celsius, Three Arrows, FTX в 2022),
  продажи майнеров. Падение обычно длится, пока не сдадутся все, кто купил дорого, — в прошлых циклах цена уходила
  ниже средней цены покупки (MVRV ниже 1). В этом цикле так может и не случиться.
- **Почему ритм — четыре года.** Халвинги идут раз в четыре года и каждый раз сокращают продажи майнеров. Но фон
  ФРС каждый раз был разным (блок 7), а сам ритм поддерживает то, что все его ждут. Отделить причины нельзя.
""")

# ---------- 2. халвинги и затухание ----------
st.header("2. Вершины после халвингов и затухание цикла")
learn.tags("опережающий", "нарратив")
st.dataframe(hp.style.format({"Рост от халвинга до вершины, %": "{:+,.0f}"}), hide_index=True, width="stretch")
st.markdown(f"Вершина каждый раз приходила через {hp['Дней после халвинга'].min()}–{hp['Дней после халвинга'].max()} "
            f"дней после халвинга, но рост от халвинга до вершины тает: "
            + " → ".join(f"{x:,.0f}%".replace(",", " ") for x in hp["Рост от халвинга до вершины, %"])
            + ". Случаев четыре — совпадение вполне возможно.")
st.plotly_chart(grouped_bars(vol.to_frame("Волатильность, % годовых"), units="%", height=260), width="stretch")
st.caption("Годовая волатильность биткоина. Чем больше рынок и чем больше в нём крупных держателей (ETF, компании), "
           "тем меньше размах — и тем мельче циклы.")

with learn.how_it_works("Как пользоваться циклом и где он обманет"):
    st.markdown("""
- **Как ориентир.** Цикл подсказывает, где вы скорее всего находитесь: ранний рост, поздний рост, падение,
  дно. Сверяйте с MVRV (блок 7), фандингом (блок 1) и мировыми деньгами (блок 4) — если все говорят одно, уверенности
  больше.
- **Где обманет.** Все ждут цикла и пытаются опередить его — поэтому вершины и дно могут сдвигаться. Если
  мировые деньги резко подешевеют или подорожают, они перекроют халвинг. И с каждым циклом рынок всё больше похож на
  обычный рисковый актив.
""")


# ---------- примеры ----------
def cycle(peak: str, text: str) -> None:
    row = bears[bears["Вершина"] == pd.Timestamp(peak).date()].iloc[0]
    a = pd.Timestamp(peak)
    w = p[a - pd.Timedelta(days=400):a + pd.Timedelta(days=800)]
    c = st.columns(3)
    c[0].metric("Глубина", f"{row['Глубина, %']:.0f}%", border=True)
    c[1].metric("Дней до дна", f"{row['Дней до дна']}", border=True)
    back = row["Дней от дна до новой вершины"]
    c[2].metric("Дней до нового рекорда", "ещё нет" if pd.isna(back) else f"{back:.0f}", border=True)
    st.plotly_chart(line_chart({"Биткоин": w}, units="$", height=280), width="stretch")
    st.markdown(text)


learn.examples([
    Example("2013–2015", lambda: cycle(
        "2013-12-04", "Первый большой цикл: рост в десятки раз за год, вершина через год после первого халвинга. "
                      "Разворот запустил запрет банкам Китая работать с биткоином (5 декабря 2013 года), а в феврале "
                      "2014 года остановила вывод и обанкротилась крупнейшая биржа Mt. Gox.")),
    Example("2017–2018", lambda: cycle(
        "2017-12-16", "Бум ICO и розничных инвесторов. Вершина через полтора года после халвинга, затем год падения: "
                      "взлом биржи Coincheck, ограничения в Южной Корее, запрет рекламы крипты в Facebook и Google, "
                      "лопнувшие ICO.")),
    Example("2021–2022", lambda: cycle(
        "2021-11-08", "Мягкие деньги пандемии, приход компаний и фондов. Вершина через полтора года после халвинга, "
                      "затем подъём ставок ФРС и крахи Terra, Celsius, FTX.")),
    Example("2024–2026: мельче прошлых", lambda: cycle(
        "2025-10-06", "Вершина пришла по расписанию — через полтора года после халвинга. Но рост до неё был намного "
                      "скромнее прошлых, а падение пока мельче: ETF и компании-казначейства сделали рынок тяжелее и "
                      "спокойнее. Цикл есть, но он затухает."), normal=False),
], key="cycles")

