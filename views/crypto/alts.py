"""Крипта, блок 3. Альткоины и токеномика: альткоины идут за биткоином, но с большим собственным риском; почему они
падают глубже, откуда постоянное давление продаж (разлоки, разводнение) и что важно при торговле ими."""
import numpy as np
import pandas as pd
import streamlit as st

from core import crypto, learn, ui
from core.charts import line_chart
from core.learn import Example
from core.transforms import cut

NUM = 7
PERIODS = {"3 года": 3, "5 лет": 5, "Вся история": None}


@st.cache_data(ttl=3600, show_spinner=False)
def unlocks():
    return crypto.upcoming_unlocks()


# ---------- данные ----------
btc = ui.load("BTC-USD").dropna()
eth = ui.load("ETH-USD").dropna()
t = crypto.alt_table(ui.load)
eb = (eth / btc).dropna()
eb_2021 = float(eb["2021"].max())
btc_dd = float((btc.iloc[-1] / btc.max() - 1) * 100)
worse = int((t["От максимума сейчас, %"] < btc_dd).sum())
eb_90 = float((eb.iloc[-1] / eb[:eb.index[-1] - pd.Timedelta(days=90)].iloc[-1] - 1) * 100)
eb_low = eb["2024":].min()
season = ("Сейчас сезон альткоинов: эфир за 90 дней обогнал биткоин на {:+.0f}%." if eb_90 > 15 else
          "Сейчас альткоины отстают: эфир к биткоину {:+.0f}% за 90 дней." if eb_90 < -5 else
          "Сейчас альткоины идут вровень с биткоином: эфир к биткоину {:+.0f}% за 90 дней.").format(eb_90)

# ---------- шапка ----------
learn.crypto_header(crypto.BY_NUM[NUM], len(crypto.BLOCKS),
                    "Альткоины — все монеты, кроме биткоина: эфир, Solana, тысячи мелких токенов. Блок идёт от того, "
                    "что их двигает (части 1–2), к тому, что давит на них изнутри (3), и к правилам торговли (4).")

learn.takeaway(f"Альткоины рискованнее биткоина: сейчас {worse} из {len(t)} крупных альткоинов дальше от своих "
               f"максимумов, чем он. {season}", "warn" if eb_90 < -5 else "neutral")

c = st.columns(3)
c[0].metric("1 · Худшая просадка альткоинов", f"{t.iloc[:, 4].median():.0f}%", "медиана с 2021 года",
            delta_color="off", border=True, help=f"У биткоина сейчас {btc_dd:.0f}% от максимума.")
c[1].metric("2 · Эфир к биткоину", f"{eb.iloc[-1]:.4f}", f"{eb_90:+.0f}% за 90 дней · пик 2021: {eb_2021:.4f}",
            delta_color="off", border=True, help="Сколько биткоинов стоит один эфир. Растёт — альткоины обгоняют.")
c[2].metric("4 · Во сколько раз волатильнее", f"×{t['Волатильнее биткоина, раз'].median():.1f}",
            "медиана, к биткоину", delta_color="off", border=True)

years = PERIODS[st.segmented_control("Период графиков", list(PERIODS), default="5 лет", key="period") or "5 лет"]

# ---------- 1. тень биткоина ----------
with learn.part_section(NUM, "follow"):
    st.markdown("Деньги в крипту обычно приходят через биткоин и уходят через него же. Когда биткоин падает, из "
                "альткоинов бегут первыми: их рынок тоньше и плеча на нём больше (блок 1).")
    st.markdown("**Доказательство:** крупнейшие альткоины против биткоина, недели с 2021 года.")
    st.dataframe(t.drop(columns=["Бета к биткоину", "Корреляция"])
                 .style.format({"Волатильнее биткоина, раз": "×{:.1f}", "От максимума сейчас, %": "{:.0f}",
                                t.columns[4]: "{:.0f}"}), width="stretch")
    st.caption(f"На 1% движения биткоина они сдвигаются в среднем примерно на {t['Бета к биткоину'].median():.1f}% — "
               f"почти один к одному; больше колебания у них за счёт собственного риска. Список — сегодняшние лидеры: "
               f"тысячи монет 2017 и 2021 годов исчезли совсем, так что реальная картина ещё хуже.")
    pick = st.selectbox("Сравнить с биткоином", list(crypto.ALTS.values()), key="alt_pick")
    key = next(k for k, v in crypto.ALTS.items() if v == pick)
    a = cut(ui.load(key).dropna(), years)
    b = btc[a.index[0]:]
    st.plotly_chart(line_chart({pick: a / a.iloc[0] * 100, "Биткоин": b / b.iloc[0] * 100}, height=280),
                    width="stretch")
    st.caption("Цена в начале периода = 100.")

# ---------- 2. сезон альткоинов ----------
with learn.part_section(NUM, "season"):
    st.markdown("Иногда альткоины несколько месяцев подряд растут быстрее биткоина — это называют сезоном альткоинов. "
                "Обычно — на поздней стадии бычьего рынка, когда прибыль перекладывают в риск.")
    st.markdown(f"**Доказательство:** курс эфира к биткоину. {season}")
    st.plotly_chart(line_chart({"Эфир к биткоину": cut(eb, years)}, height=260), width="stretch")
    st.caption(f"Минимум с 2024 года — {eb_low:.4f}; рывки бывали и после 2021 года (конец 2024, лето 2025), но "
               f"короткие.")
    eth_in, btc_in = ui.load("ETF_FLOW_ETH").sum() / 1000, ui.load("ETF_FLOW_BTC").sum() / 1000
    with st.expander("Почему сезонов стало меньше"):
        st.markdown(f"""
- **Новые деньги приходят в биткоин.** ETF, компании-казначейства и фонды покупают в основном биткоин (блок 6).
  Приток в эфир-ETF с запуска — ${eth_in:.0f} млрд против ${btc_in:.0f} млрд у биткоин-ETF.
- **Монет стало слишком много.** В 2017 году деньги делились примерно на тысячу альткоинов, сейчас — на десятки тысяч.
- **Разводнение** — часть 3.
""")

# ---------- 3. разводнение и разлоки ----------
with learn.part_section(NUM, "supply"):
    st.markdown("У биткоина расписание выпуска одно для всех. У большинства альткоинов — нет: команда, венчурные фонды "
                "и ранние инвесторы получают токены, которые **разблокируются** по расписанию, — и многие продают. "
                "**Капитализация** — цена × токены в обращении; **FDV** — цена × все токены, которые когда-либо "
                "выйдут. Если в обращении 15%, остальные 85% ещё придут на рынок.")
    ul = unlocks()
    if ul is None:
        st.warning("Календарь trade-news не отвечает.")
    elif not ul:
        st.info("Крупных разлоков в ближайшие 30 дней нет.")
    else:
        df = pd.DataFrame([{"Дата": e["date"], "Токен": ", ".join(e["assets"]), "Доля предложения, %": e.get("size"),
                            "Крупный": "да" if e.get("major") else ""} for e in ul])
        df = df.sort_values(["Крупный", "Доля предложения, %"], ascending=False).head(15).sort_values("Дата")
        st.markdown("**Ближайшие разлоки** — факт на сегодня, не доказательство (календарь trade-news, DefiLlama):")
        st.dataframe(df.style.format({"Доля предложения, %": "{:.1f}"}, na_rep="—"), hide_index=True,
                     width="stretch")
        st.caption("Доля — от уже разблокированного объёма. Отраслевые разборы (например, Keyrock, 2024) находят, что "
                   "цена часто слабеет за недели до крупного разлока; своя проверка появится, когда накопится "
                   "история.")

# ---------- 4. как торговать альтами ----------
with learn.part_section(NUM, "trade"):
    st.markdown(f"""
- **Стоп по волатильности.** Альткоин колеблется в {t['Волатильнее биткоина, раз'].median():.1f} раза сильнее
  биткоина (медиана) — при том же риске позиция должна быть примерно во столько же раз меньше (блок 10).
- **Ликвидность.** У мелких монет спред — 0,2–1%, в стакане мало заявок: крупная заявка по рынку сдвигает цену против
  вас, стоп исполняется хуже.
- **Листинги и делистинги.** После выхода на крупную биржу цену часто разгоняют, потом она сдувается. Делистинг —
  обвал и закрытие фьючерсов.
- **Плечо опаснее.** Поддерживающая маржа выше, фандинг чаще, каскады глубже (блок 1).
- **Перед крупным разлоком** держать лонг рискованно (часть 3).
""")
    st.caption("Кроме первого пункта (арифметика), это практические правила трейдеров, а не проверенные здесь данные.")


# ---------- примеры ----------
def compare(start: str, end: str, text: str) -> None:
    rows = {}
    for k, name in [("BTC-USD", "Биткоин")] + list(crypto.ALTS.items())[:4]:
        s = ui.load(k).dropna()[start:end]
        if len(s) > 1:
            rows[name] = s / s.iloc[0] * 100
    st.plotly_chart(line_chart(rows, height=300), width="stretch")
    st.markdown(" · ".join(f"{n}: {(s.iloc[-1] / 100 - 1) * 100:+.0f}%" for n, s in rows.items()))
    st.markdown(text)


learn.examples([
    Example("2021: сезон альткоинов", lambda: compare(
        "2021-01-01", "2021-11-10",
        "Мягкие деньги, бум DeFi и NFT: деньги текли из биткоина в рискованные монеты, эфир к биткоину вырос в "
        "разы. Классический сезон альткоинов на поздней стадии бычьего рынка.")),
    Example("2022: падают глубже биткоина", lambda: compare(
        "2021-11-10", "2022-12-31",
        "ФРС подняла ставки, рухнули Terra и FTX. Биткоин потерял около трёх четвертей, крупные альткоины — больше: "
        "в медвежьем рынке плечо альткоинов работает против держателя.")),
    Example("2024–2026: биткоин без альткоинов", lambda: compare(
        "2023-10-01", str(btc.index[-1].date()),
        "Новые деньги через ETF и компании пришли в биткоин. Альткоины отстали, многие так и не вернулись к "
        "максимумам 2021 года, а эфир к биткоину обновлял минимумы. Рост биткоина больше не гарантирует сезона "
        "альткоинов."), normal=False),
], key="alts")

st.divider()
st.subheader("Как части блока связаны")
st.graphviz_chart(learn.block_graph(NUM), width="stretch")
st.caption("Синие — части этого блока, серые — соседние блоки. Стрелки не показывают силу связи.")
