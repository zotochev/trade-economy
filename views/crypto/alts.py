"""Крипта, блок 3. Альткоины и токеномика: почему альткоины — это в основном биткоин с плечом, почему они падают
глубже и откуда берётся постоянное давление продаж (разлоки, разводнение)."""
import numpy as np
import pandas as pd
import streamlit as st

from core import crypto, learn, ui
from core.charts import line_chart
from core.learn import Example
from core.transforms import cut

PERIODS = {"3 года": 3, "5 лет": 5, "Вся история": None}


@st.cache_data(ttl=3600, show_spinner=False)
def unlocks():
    return crypto.upcoming_unlocks()


# ---------- данные ----------
btc = ui.load("BTC-USD").dropna()
eth = ui.load("ETH-USD").dropna()
t = crypto.alt_table(ui.load)
eb = (eth / btc).dropna()
eb_2021 = float(eb["2021"].max())
btc_dd = float((btc.iloc[-1] / btc.max() - 1) * 100)
worse = int((t["От максимума сейчас, %"] < btc_dd).sum())

# ---------- шапка ----------
learn.crypto_header(crypto.BY_NUM[7], len(crypto.BLOCKS),
                    "Альткоины — все монеты, кроме биткоина: эфир, Solana, тысячи мелких токенов. У каждого своя "
                    "история, но двигаются они в основном вслед за биткоином — только сильнее. А у многих есть "
                    "встроенное давление продаж: команды и фонды получают токены по расписанию (разлоки) и "
                    "продают их.")

learn.takeaway(f"Альткоины — это биткоин с плечом: сейчас {worse} из {len(t)} крупных альткоинов дальше от своих "
               f"максимумов, чем биткоин. «Сезона альткоинов» нет уже несколько лет.", "warn")

c = st.columns(3)
c[0].metric("Эфир к биткоину", f"{eb.iloc[-1]:.4f}", f"пик 2021: {eb_2021:.4f}", delta_color="off", border=True,
            help="Сколько биткоинов стоит один эфир. Растёт — альткоины обгоняют биткоин.")
c[1].metric("Худшая просадка", f"{t.iloc[:, 4].median():.0f}%", "медиана с 2021 года", delta_color="off",
            border=True)
c[2].metric("Биткоин от максимума", f"{btc_dd:.0f}%", f"альткоины: медиана {t.iloc[:, 3].median():.0f}%",
            delta_color="off", border=True)

years = PERIODS[st.segmented_control("Период графиков", list(PERIODS), default="5 лет", key="period") or "5 лет"]

# ---------- 1. биткоин с плечом ----------
st.header("1. Альткоины следуют за биткоином — только сильнее")
st.markdown("Деньги в крипту обычно приходят через биткоин и уходят через него же. Когда биткоин растёт, часть "
            "прибыли перекладывают в более рискованные монеты; когда падает — из альткоинов бегут первыми, потому "
            "что их рынок тоньше и плеча на нём больше (блок 1).")
learn.tags("совпадающий", "проверен на истории")
st.dataframe(t.style.format({"Бета к биткоину": "{:.2f}", "Корреляция": "{:+.2f}", "Волатильнее биткоина, раз": "×{:.1f}",
                             "От максимума сейчас, %": "{:.0f}", t.columns[4]: "{:.0f}"}), width="stretch")
st.caption("Недельные движения с 2021 года. Это крупнейшие из выживших альткоинов: тысячи монет 2017 и 2021 годов "
           "исчезли совсем, так что реальная картина ещё хуже.")
pick = st.selectbox("Сравнить с биткоином", list(crypto.ALTS.values()), key="alt_pick")
key = next(k for k, v in crypto.ALTS.items() if v == pick)
a = cut(ui.load(key).dropna(), years)
b = btc[a.index[0]:]
st.plotly_chart(line_chart({pick: a / a.iloc[0] * 100, "Биткоин": b / b.iloc[0] * 100}, height=300), width="stretch")
st.caption("Цена в начале периода = 100.")

# ---------- 2. сезон альткоинов ----------
st.header("2. «Сезон альткоинов» — когда он бывает")
st.markdown("Иногда альткоины несколько месяцев подряд растут быстрее биткоина — это называют сезоном альткоинов. "
            "Лучший градусник — курс эфира к биткоину: растёт, когда деньги текут в рискованные монеты.")
learn.tags("совпадающий", "спорный")
st.plotly_chart(line_chart({"Эфир к биткоину": cut(eb, years)}, height=280), width="stretch")
st.caption("Сколько биткоинов стоит один эфир.")
eth_in, btc_in = ui.load("ETF_FLOW_ETH").sum() / 1000, ui.load("ETF_FLOW_BTC").sum() / 1000
with learn.how_it_works("Почему сезонов альткоинов стало меньше"):
    st.markdown(f"""
- **Новые деньги приходят в биткоин.** ETF, компании-казначейства и фонды покупают в основном биткоин (блок 6).
  Эфир-ETF есть, но приток в них с запуска — ${eth_in:.0f} млрд против ${btc_in:.0f} млрд у биткоин-ETF.
- **Монет стало слишком много.** В 2017 году деньги делились на сотни альткоинов, сейчас — на десятки тысяч.
  Каждый новый токен оттягивает спрос у старых.
- **Разводнение.** У многих токенов в обращении только малая часть: остальное получат команда и фонды позже и
  продадут. Цена растёт медленнее, чем могла бы, — предложение прибывает.
""")

# ---------- 3. токеномика и разлоки ----------
st.header("3. Токеномика: кто и когда получит токены")
st.markdown("У биткоина расписание выпуска одно для всех. У большинства альткоинов — нет: при запуске команда, "
            "венчурные фонды и ранние инвесторы получают долю токенов, которая **разблокируется** по расписанию. "
            "В день разлока у них появляется возможность продать — и многие продают.")
learn.tags("опережающий", "спорный")
with learn.how_it_works("Капитализация и полная стоимость (FDV)"):
    st.markdown("""
- **Капитализация** — цена × токены в обращении. **FDV** (полностью разводнённая стоимость) — цена × все токены,
  которые когда-либо будут выпущены.
- **Большой разрыв FDV и капитализации** — предупреждение: если в обращении 15% токенов, остальные 85% ещё
  выйдут на рынок. Чтобы цена устояла, спрос должен вырасти в разы.
- **Что говорят исследования.** Отраслевые разборы (например, Keyrock, 2024) находят, что цена часто слабеет
  заранее, за недели до крупного разлока, а не в сам день. Своей проверки на истории здесь пока нет — календарь
  разлоков в trade-news копится с октября 2026 года.
""")
ul = unlocks()
if ul is None:
    st.warning("Календарь trade-news не отвечает.")
elif not ul:
    st.info("Крупных разлоков в ближайшие 30 дней нет.")
else:
    df = pd.DataFrame([{"Дата": e["date"], "Токен": ", ".join(e["assets"]), "Доля предложения, %": e.get("size"),
                        "Крупный": "да" if e.get("major") else ""} for e in ul])
    df = df.sort_values(["Крупный", "Доля предложения, %"], ascending=False).head(15).sort_values("Дата")
    st.markdown("**Ближайшие разлоки** (крупнейшие за 30 дней, календарь trade-news по данным DefiLlama):")
    st.dataframe(df.style.format({"Доля предложения, %": "{:.1f}"}, na_rep="—"), hide_index=True, width="stretch")
    st.caption("Доля — от уже разблокированного объёма. Большинство этих токенов мелкие: на биткоин они не влияют, "
               "но для держателя такого токена это главный риск месяца.")


# ---------- примеры ----------
def compare(start: str, end: str, text: str) -> None:
    rows = {}
    for k, name in [("BTC-USD", "Биткоин")] + list(crypto.ALTS.items())[:4]:
        s = ui.load(k).dropna()[start:end]
        if len(s) > 1:
            rows[name] = s / s.iloc[0] * 100
    st.plotly_chart(line_chart(rows, height=300), width="stretch")
    st.markdown(" · ".join(f"{n}: {(s.iloc[-1] / 100 - 1) * 100:+.0f}%" for n, s in rows.items()))
    st.markdown(text)


learn.examples([
    Example("2021: сезон альткоинов", lambda: compare(
        "2021-01-01", "2021-11-10",
        "Мягкие деньги, бум DeFi и NFT: деньги текли из биткоина в рискованные монеты, эфир к биткоину вырос в "
        "разы. Классический сезон альткоинов на поздней стадии бычьего рынка.")),
    Example("2022: падают глубже биткоина", lambda: compare(
        "2021-11-10", "2022-12-31",
        "ФРС подняла ставки, рухнули Terra и FTX. Биткоин потерял около трёх четвертей, крупные альткоины — больше: "
        "в медвежьем рынке плечо альткоинов работает против держателя.")),
    Example("2024–2026: биткоин без альткоинов", lambda: compare(
        "2023-10-01", str(btc.index[-1].date()),
        "Новые деньги через ETF и компании пришли в биткоин. Альткоины отстали, многие так и не вернулись к "
        "максимумам 2021 года, а эфир к биткоину обновлял минимумы. Рост биткоина больше не гарантирует сезона "
        "альткоинов."), normal=False),
], key="alts")

st.divider()
st.markdown("**Дальше.** Плечо на альткоинах выше, а каскады начинаются там — блок 1. Циклы, внутри которых бывают "
            "сезоны альткоинов, — блок 8.")
