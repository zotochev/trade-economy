def answer(num: int) -> tuple[str, str, str]:
    if num == 1:
        w = crypto.weekly(ui.load)
        head, color, c = crypto.verdict(w)
        _, after = crypto.era_corr(w)
        return head, (f"Корреляция с Nasdaq за год {c:+.2f}: Nasdaq объясняет ≈{c * c * 100:.0f}% движений биткоина "
                      f"(в среднем с 2020 года {after:+.2f}). Связь с ликвидностью ФРС спорная."), color
    if num == 2:
        bas, bill = crypto.basis(ui.load), ui.load("DGS3MO").dropna()
        am, lf = ui.load("COT_BTC_AM").dropna(), ui.load("COT_BTC_LEV").dropna()
        edge = float(bas.iloc[-1] - bill.iloc[-1] - 0.75)
        head = ("Базисная сделка выгодна: часть притока в ETF — арбитраж" if edge > 0.5 else
                "Базисная сделка убыточна — арбитражный приток в ETF иссякает" if edge < -0.5 else
                "Базисная сделка на грани безубыточности")
        return head, (f"Базис CME ≈{bas.iloc[-1]:.1f}% годовых против {bill.iloc[-1]:.1f}% у векселей. На CME "
                      f"управляющие активами {am.iloc[-1]:+.0f}%, фонды с плечом {lf.iloc[-1]:+.0f}% открытого "
                      f"интереса."), "orange" if edge < -0.5 else "gray"
    if num == 3:
        ev = crypto.event_study(ui.load)
        by = ev.groupby("Вид")["За 2 дня, %"].mean()
        return ("Аварии внутри крипты бьют сильнее регуляторов",
                f"За 2 дня после событий с 2017 года: смягчение правил {by['рег+']:+.1f}%, ужесточение "
                f"{by['рег−']:+.1f}%, аварии {by['шок']:+.0f}%. Регуляторные новости рынок отыгрывает заранее.", "gray")
    if num == 4:
        head, color, f, pct = crypto.lev_verdict(ui.load)
        odds = crypto.liq_odds(crypto.candles(ui.load), [10], {"м": 30})
        return head, (f"Фандинг за неделю {f:.1f}% годовых — выше, чем в {pct:.0f}% дней с 2019 года. С плечом 10x "
                      f"лонг закрывался бы биржей в течение месяца в {odds.iloc[0, 0]:.0f}% случаев."), color
    if num == 5:
        g = crypto.supply_growth(ui.load)
        pct = float((g["2019":] < g.iloc[-1]).mean() * 100)
        tot = ui.load("STABLE_TOTAL")
        head = ("Топливо прибывает: стейблкоинов становится заметно больше" if pct >= 70 else
                "Топливо почти не прибывает" if pct <= 30 else "Топливо прибывает в обычном темпе")
        return head, (f"Стейблкоинов в обращении ${tot.iloc[-1]:.0f} млрд, {g.iloc[-1]:+.1f}% за 90 дней. Рост "
                      f"идёт вместе с ценой, а не заранее."), "orange" if pct <= 30 else "gray"
    if num == 6:
        o = crypto.onchain(ui.load)
        mv = float(o["mvrv"].iloc[-1])
        head = ("Держатели в большой прибыли — рынок перегрет" if mv >= 3 else
                "Держатели в убытке — исторически зона дна" if mv < 1 else "Держатели в умеренной прибыли")
        return head, (f"MVRV {mv:.2f}: цена ${o['price'].iloc[-1]:,.0f} против средней цены покупки "
                      f"${o['realized'].iloc[-1]:,.0f}. На биржах {o['exch'].dropna().iloc[-1]:.1f}% всех монет."
                      ).replace(",", " "), "orange" if mv >= 3 else "green" if mv < 1 else "gray"
    raise KeyError(num)


left, right = st.columns([5, 1], vertical_alignment="bottom")
left.title("Карта крипты")
with right:
    learn.help_link("Справка")
st.markdown("Чтобы понимать крипту, мало смотреть на цену. Нужно видеть, **из чего она состоит** и **в какой среде "
            "живёт**. Карта собирает обе стороны: снаружи — мировые деньги и институционалы, внутри — монеты, "
            "доллары крипты, плечо и участники.")

with learn.how_it_works("Как читать карту"):
    st.markdown("""
- **Среда** — силы снаружи: ставки ФРС, доллар, фонды и регуляторы. Крипта на них не влияет, а они на неё — да.
- **Устройство** — части самой крипты: откуда берутся монеты, на какие деньги их покупают, сколько взято в
  долг, кто участники. Они толкают друг друга и создают внутренние циклы.
- **Практика** — как перевести понимание в торговлю: размер позиции, плечо, календарь событий.
- **Связи и петли** внизу — как одна часть передаёт импульс другой. Самая важная для трейдера — петля плеча: она
  делает падения в крипте резкими.
- Блоки строятся по одному. У построенного — вывод по свежим данным и ссылка на экран.
""")

# ---------- объект в центре ----------
btc = ui.load("BTC-USD").dropna()
dd = crypto.drawdown(btc)
year = float((btc.iloc[-1] / btc[:btc.index[-1] - pd.DateOffset(years=1)].iloc[-1] - 1) * 100)
with st.container(border=True):
    st.caption("В центре · объект")
    c = st.columns(3)
    c[0].metric("Биткоин", f"${btc.iloc[-1]:,.0f}".replace(",", " "), border=True)
    c[1].metric("За год", f"{year:+.0f}%", border=True)
    c[2].metric("От максимума", f"{dd.iloc[-1]:.0f}%", f"максимум ${btc.max():,.0f}".replace(",", " "),
                delta_color="off", border=True)

for side, title in (("среда", "Среда: что давит снаружи"), ("устройство", "Устройство: из чего крипта состоит"),
                    ("практика", "Практика: как с этим торговать")):
    st.subheader(title)
    for b in [b for b in crypto.BLOCKS if b.side == side]:
        with st.container(border=True):
            left, right = st.columns([5, 1], vertical_alignment="center")
            with left:
                st.caption(f"Блок {b.num} · {b.title}")
                if b.page:
                    try:
                        head, why, color = answer(b.num)
                        st.markdown(f"#### {ICON[color]} {head}")
                        st.markdown(why)
                    except Exception as e:  # один недоступный ряд не должен гасить всю карту
                        st.warning(f"Нет данных: {e}")
                else:
                    st.markdown(f"{b.about}  \n:gray[блок в разработке]")
            with right:
                if b.page:
                    st.page_link(b.page, label="Открыть блок", icon="➡️")

st.subheader("Связи: как части толкают друг друга")
st.markdown("\n".join(f"- **{a}** → **{b}**: {what}" for a, b, what in LINKS))
st.subheader("Петли: где цепочка возвращается в цену")
st.markdown("Петли объясняют, почему крипта ходит рывками: движение само себя усиливает, пока не кончится топливо.")
st.markdown("\n".join(f"- **{name}.** {what}" for name, what in LOOPS))
