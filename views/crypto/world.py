"""Крипта, блок 1. Крипта и мировые деньги: насколько биткоин ходит вместе с акциями роста, долларом, ставками
и ликвидностью ФРС — и когда эта связь рвётся."""
import pandas as pd
import streamlit as st

from core import crypto, learn, ui
from core.charts import dual_axis_chart, line_chart
from core.learn import Example
from core.transforms import cut

PERIODS = {"3 года": 3, "5 лет": 5, "Вся история": None}

# ---------- данные ----------
w = crypto.weekly(ui.load)
btc = ui.load("BTC-USD").dropna()
ndx = ui.load("^IXIC").dropna()
corr = crypto.rolling_corr(w)
table = crypto.by_year(w)
before, after = crypto.era_corr(w)
sell = crypto.selloff_weeks(w)
liq_c = crypto.liquidity_corr(ui.load)
vol_now = float(table["Во сколько раз волатильнее Nasdaq"].iloc[-3:].mean())
dd_btc, dd_ndx = crypto.drawdown(btc), crypto.drawdown(ndx)

# ---------- шапка ----------
learn.crypto_header(crypto.BY_NUM[1], len(crypto.BLOCKS),
                    "Крипта не висит в пустоте: её покупают на те же доллары, что и акции. Когда ФРС дорожит деньги, "
                    "а доллар крепнет, у всех рисковых активов меньше покупателей — и у биткоина тоже. Этот блок "
                    "показывает, насколько сильна эта связь сейчас и как она менялась.")

head, color, c_now = crypto.verdict(w)
learn.takeaway(f"{head}. Корреляция недельных движений с Nasdaq за полгода {c_now:+.2f} (до 2020 года — "
               f"{before:+.2f}, с 2020 — {after:+.2f}). При этом биткоин в {vol_now:.1f} раза волатильнее Nasdaq и "
               f"сейчас на {abs(dd_btc.iloc[-1]):.0f}% ниже своего максимума против {abs(dd_ndx.iloc[-1]):.0f}% у Nasdaq: "
               f"внутренние силы крипты по-прежнему двигают цену сильнее мировых денег.",
               {"orange": "warn", "blue": "neutral"}.get(color, "neutral"))

c = st.columns(4)
c[0].metric("Биткоин", f"${btc.iloc[-1]:,.0f}".replace(",", " "), f"{dd_btc.iloc[-1]:.0f}% от максимума",
            delta_color="off", border=True)
c[1].metric("Связь с Nasdaq", f"{c_now:+.2f}", "корреляция за 26 недель", delta_color="off", border=True,
            help="От −1 до +1. Около 0 — движутся независимо, +1 — всегда в одну сторону. Выше 0,4 — сильная связь.")
c[2].metric("Волатильность", f"×{vol_now:.1f}", "к Nasdaq, за 3 года", delta_color="off", border=True,
            help="Во сколько раз недельные колебания биткоина больше, чем у Nasdaq.")
c[3].metric("Связь с ликвидностью ФРС", f"{liq_c:+.2f}", "изменения за 3 мес., с 2020", delta_color="off",
            border=True, help="Корреляция изменений биткоина и чистой ликвидности ФРС (баланс − счёт Минфина − "
                              "обратное РЕПО). Ниже 0,3 — слабая связь.")

years = PERIODS[st.segmented_control("Период графиков", list(PERIODS), default="5 лет", key="period") or "5 лет"]

# ---------- 1. рисковый актив ----------
st.header("1. С 2020 года биткоин — рисковый актив")
st.markdown("До пандемии биткоин жил своей жизнью: его движения почти не совпадали с акциями. В 2020 году пришли "
            "фонды и компании, и биткоин начал реагировать на то же, что и акции технологических компаний: "
            "ставки и аппетит к риску.")
learn.tags("совпадающий", "проверен на истории")
st.plotly_chart(line_chart({"Корреляция с Nasdaq за 26 недель": cut(corr, years)}, zero_line=True, height=300),
                width="stretch")
st.caption("Выше нуля — биткоин и Nasdaq чаще движутся в одну сторону. Линия скачет: связь то усиливается, то "
           "пропадает на месяцы.")
st.dataframe(table.style.format("{:+.2f}", subset=["С Nasdaq", "С долларом", "С реальной ставкой"])
             .format("×{:.1f}", subset=["Во сколько раз волатильнее Nasdaq"]), width="stretch")
st.caption("Корреляции недельных движений по годам. Доллар — широкий индекс ФРС, реальная ставка — доходность "
           "10-летних TIPS.")

with learn.how_it_works():
    st.markdown(f"""
- **Почему крипта зависит от ставок.** У биткоина нет прибыли и купонов: вся его цена — ожидание, что завтра
  купят дороже. Когда безрисковые облигации дают высокий доход, ждать дорого, и деньги уходят из самых спекулятивных
  активов первыми. Когда ставки низкие и денег много — приходят первыми.
- **Почему против доллара.** Сильный доллар значит, что деньги в мире дорожают и стягиваются в США, в
  гособлигации. Связь с долларом в большинство лет отрицательная.
- **Волатильность.** Биткоин колеблется в {vol_now:.1f} раза сильнее Nasdaq (за последние 3 года). Поэтому даже при той же причине
  движение крипты больше.
- **Чего связь не говорит.** Корреляция {after:+.2f} — это слабо: большая часть движений биткоина
  объясняется не Nasdaq, а внутренними силами крипты (плечо, потоки ETF, предложение — блоки 2–7).
""")

# ---------- 2. плохие дни для акций ----------
st.header("2. Когда акции падают")
st.markdown(f"С 2020 года было **{sell['n']} недель**, когда Nasdaq падал больше чем на 3%. Биткоин падал вместе с "
            f"ним в **{sell['down_share']:.0f}%** таких недель, медиана: биткоин {sell['btc_median']:+.1f}%, Nasdaq "
            f"{sell['ndx_median']:+.1f}%. За одну неделю биткоин не обязательно падает сильнее. Но в затяжном "
            f"ужесточении ФРС разница огромная — смотрите просадки на графике ниже.")
learn.tags("совпадающий", "проверен на истории")
st.plotly_chart(line_chart({"Биткоин": cut(dd_btc, years), "Nasdaq": cut(dd_ndx, years)}, units="%", height=320),
                width="stretch")
st.caption("Просадка от предыдущего максимума, %. Ноль — цена на рекорде.")

# ---------- 3. ликвидность ----------
st.header("3. Ликвидность ФРС — популярная, но слабая связь")
st.markdown(f"В крипто-сообществе любят говорить, что биткоин следует за «печатанием денег». На данных с 2020 года "
            f"связь изменений за 3 месяца — **{liq_c:+.2f}**: она есть, но объясняет малую часть движений.")
learn.tags("совпадающий", "спорный")
liq = crypto.net_liquidity(ui.load)
st.plotly_chart(dual_axis_chart(("Биткоин", cut(btc, years), "$"), ("Чистая ликвидность ФРС", cut(liq, years),
                                                                     "трлн $"), height=320), width="stretch")
st.caption("Чистая ликвидность = баланс ФРС − счёт Минфина (TGA) − обратное РЕПО: деньги, реально доступные рынку.")

with learn.how_it_works("Почему связь слабая"):
    st.markdown("""
- **Ликвидность — один из многих источников денег.** Кредит банков, приток в ETF, стейблкоины, деньги из-за
  пределов США — всё это двигает крипту, а в чистую ликвидность ФРС не входит.
- **Картинка обманчива.** На графиках за 2020–2021 годы обе линии растут — глаз видит связь. Но в отдельные
  кварталы они часто расходятся. Подробнее о ликвидности — в слое 2 «Политика ФРС».
""")


# ---------- примеры ----------
def show_window(start: str, end: str, text: str) -> None:
    r = crypto.window(ui.load, start, end)
    c = st.columns(2)
    c[0].metric("Биткоин", f"{r['Биткоин']:+.0f}%", border=True)
    c[1].metric("Nasdaq", f"{r['Nasdaq']:+.0f}%", border=True)
    st.plotly_chart(line_chart({"Биткоин": (btc[start:end] / btc[:start].iloc[-1] * 100),
                                "Nasdaq": (ndx[start:end] / ndx[:start].iloc[-1] * 100)}, height=280),
                    width="stretch")
    st.caption("Цена в начале периода = 100.")
    st.markdown(text)


learn.examples([
    Example("2022: ФРС поднимает ставки", lambda: show_window(
        "2021-11-08", "2022-11-21",
        "ФРС подняла ставку почти с нуля до 4% с небольшим за год. Все рисковые активы упали, биткоин — намного сильнее Nasdaq: "
        "самые спекулятивные активы теряют первыми. Внутри крипты это усилили банкротства (Terra, Celsius, FTX).")),
    Example("Март 2020: паника", lambda: show_window(
        "2020-02-19", "2020-03-23",
        "Когда всем срочно нужны доллары, продают всё ликвидное. Биткоин упал вместе с акциями, "
        "«цифровое золото» не защитило. Вернулся вместе с ними, когда ФРС залила рынок деньгами.")),
    Example("Август 2024: сворачивание керри-трейда", lambda: show_window(
        "2024-07-31", "2024-08-05",
        "Банк Японии поднял ставку, иена резко укрепилась, фонды закрывали позиции, взятые на дешёвые иены, и "
        "продавали всё подряд. Биткоин упал сильнее Nasdaq: рисковый актив с плечом страдает первым.")),
    Example("Ноябрь 2022: крах FTX", lambda: show_window(
        "2022-11-04", "2022-11-21",
        "Рухнула одна из крупнейших бирж. Nasdaq в эти дни рос, а биткоин резко упал. Внутренний шок "
        "крипты мировым деньгам неважен — связь с акциями на время пропадает."), normal=False),
    Example("Март 2023: банковский кризис", lambda: show_window(
        "2023-03-08", "2023-03-31",
        "Обанкротились банки SVB и Signature. Акции нервничали, а биткоин заметно вырос: часть инвесторов "
        "увидела в нём защиту от проблем банков. Связь с акциями перевернулась на несколько недель."),
            normal=False),
    Example("Конец 2023 — начало 2024: запуск ETF", lambda: show_window(
        "2023-10-01", "2024-03-14",
        "Ожидание, а затем запуск спотовых биткоин-ETF в США привели в крипту новые деньги. Биткоин вырос намного "
        "сильнее Nasdaq, хотя ставки ФРС были на максимуме. Внутренний поток важнее мировых денег — "
        "об этом блок 2."), normal=False),
], key="world")

