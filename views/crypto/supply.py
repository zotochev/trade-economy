"""Крипта, блок 7. Предложение и держатели: откуда берутся новые монеты, когда майнеры вынуждены продавать, по
какой цене купили нынешние держатели (реализованная цена, MVRV) и сколько монет лежит на биржах."""
import pandas as pd
import streamlit as st

from core import crypto, learn, ui
from core.charts import dual_axis_chart, line_chart
from core.learn import Example
from core.transforms import cut

PERIODS = {"5 лет": 5, "10 лет": 10, "Вся история": None}

# ---------- данные ----------
o = crypto.onchain(ui.load)
mv = float(o["mvrv"].iloc[-1])
mv_pct = float((o["mvrv"]["2013":] < mv).mean() * 100)
mt = crypto.mvrv_table(ui.load)
iss, sup = ui.load("CM_ISS"), ui.load("CM_SUPPLY")
iss_usd = float(iss.iloc[-30:].mean() * o["price"].iloc[-1] / 1e6)
infl = float(iss.iloc[-365:].sum() / sup.iloc[-1] * 100)
etf = ui.load("ETF_FLOW_BTC")
etf_day = float(etf[-250:].abs().mean())
hp = crypto.hashprice(ui.load)
hp_pct = float((hp["2020":] < hp.iloc[-1]).mean() * 100)
hr = crypto.hash_ribbon(ui.load)
cyc = crypto.mvrv_cycle_peaks(ui.load)

# ---------- шапка ----------
learn.crypto_header(crypto.BY_NUM[6], len(crypto.BLOCKS),
                    "Новых биткоинов выпускается всё меньше: раз в четыре года награда майнерам падает вдвое "
                    "(халвинг), и всего монет никогда не будет больше 21 млн. Но цену двигает не только выпуск, "
                    "а то, **кто держит** уже выпущенные монеты и по какой цене он их купил: тот, кто в большой "
                    "прибыли, охотнее продаёт, тот, кто в убытке, — держит или сдаётся.")

zone = ("рынок перегрет: держатели в большой прибыли" if mv >= 3 else
        "держатели в убытке — исторически лучшие точки входа" if mv < 1 else
        "держатели в умеренной прибыли — середина цикла")
learn.takeaway(f"MVRV {mv:.2f}: {zone}. Цену теперь решает спрос, а не выпуск новых монет.",
               "warn" if mv >= 3 else "good" if mv < 1 else "neutral")

c = st.columns(3)
c[0].metric("MVRV", f"{mv:.2f}", f"выше {mv_pct:.0f}% дней с 2013", delta_color="off", border=True,
            help="Рыночная капитализация к реализованной: во сколько раз рынок дороже средней цены, по которой "
                 "монеты последний раз меняли владельца.")
c[1].metric("Реализованная цена", f"${o['realized'].iloc[-1]:,.0f}".replace(",", " "), "средняя цена покупки",
            delta_color="off", border=True)
c[2].metric("Новых монет в год", f"{infl:.2f}%", f"≈${iss_usd:.0f} млн в день", delta_color="off", border=True,
            help="Инфляция биткоина: выпуск за год к монетам в обращении.")

years = PERIODS[st.segmented_control("Период графиков", list(PERIODS), default="10 лет", key="period") or "10 лет"]

# ---------- 1. держатели ----------
st.header("1. По какой цене купили держатели")
st.markdown("Блокчейн биткоина открыт: видно, когда каждая монета перемещалась последний раз и сколько тогда стоила. "
            "Среднее по всем монетам — **реализованная цена**, грубо — средняя цена покупки всех держателей. "
            "**MVRV** — во сколько раз рынок выше неё.")
learn.tags("опережающий", "спорный")
st.plotly_chart(line_chart({"Цена": cut(o["price"], years), "Реализованная цена": cut(o["realized"], years)},
                           units="$", height=320), width="stretch")
st.dataframe(mt.style.format({"Цена через год, медиана %": "{:+.0f}", "Через год выше, % дней": "{:.0f}"}),
             width="stretch")
st.caption("Дни с 2013 года по уровню MVRV и что было с ценой через год; строка «все дни» — для сравнения. Соседние "
           "дни почти одинаковы: независимых случаев — по сути, четыре цикла, поэтому это ориентир, а не закон.")
st.markdown("**Пики MVRV слабеют от цикла к циклу:** "
            + " → ".join(f"{r['Пик MVRV']:.1f} ({r['Дата пика']:%m.%Y})" for _, r in cyc.iterrows())
            + ". Пик MVRV не всегда совпадает с вершиной цены (в 2021 году — весной, а цена — в ноябре). Рынок "
              "становится больше и спокойнее — «перегрев» наступает при всё меньшем MVRV.")

with learn.how_it_works():
    st.markdown("""
- **Почему ниже 1 — дно.** Когда цена ниже средней цены покупки, большинство держателей в убытке. Продают те, кто
  сдался; остальные не продают в убыток. Продавцы кончаются — и рынок разворачивается.
- **Почему высокий MVRV — риск.** Держатели в большой прибыли: каждый рост встречает фиксацию прибыли
  долгосрочными держателями. Это «тормоз держателей» с карты.
- **Ограничения.** Монеты, потерянные навсегда (несколько миллионов BTC), числятся по старой цене: они занижают
  реализованную цену и завышают MVRV. Монеты внутри ETF и бирж перемещаются по своим правилам. Циклов всего
  четыре.
""")

# ---------- 2. майнеры ----------
st.header("2. Майнеры: выпуск и вынужденные продажи")
st.markdown(f"Майнеры получают новые монеты за каждый блок и продают их, чтобы платить за электричество и "
            f"оборудование. Сейчас доход на единицу мощности ниже, чем в {hp_pct:.0f}% времени с 2020 года: после "
            f"халвинга награда упала вдвое, а мощность сети растёт.")
learn.tags("совпадающий", "спорный")
with st.expander("🔬 Подробнее для продвинутых: доход майнеров и «капитуляция майнеров»"):
    st.plotly_chart(dual_axis_chart(("Доход майнеров", cut(hp, years), "$ в день на PH/s"),
                                    ("Хешрейт", cut(ui.load("CM_HASH") / 1e6, years), "EH/s"), height=300),
                    width="stretch")
    st.caption("Доход на единицу мощности (hashprice) = выручка майнеров за день / хешрейт. Падает — майнерам тяжелее, "
               "слабые выключают оборудование и продают запасы.")
    st.markdown(f"**Проверка популярного сигнала** «конец капитуляции майнеров» (хешрейт за 30 дней снова выше, чем за "
                f"60), случаев с 2012 года: {hr['n']}. Через 90 дней цена выше в {hr['ev_up']:.0f}% случаев (медиана "
                f"{hr['ev_med']:+.0f}%), а в обычный день — в {hr['base_up']:.0f}% (медиана {hr['base_med']:+.0f}%). "
                + ("Преимущества у сигнала не видно — а случаев так мало, что разброс около ±20 п.п. Проверена упрощённая "
                   "версия, без подтверждения ценой." if hr["ev_up"] <= hr["base_up"] + 5 else "Сигнал работает."))

# ---------- 3. халвинги и биржи ----------
st.header("3. Халвинги и монеты на биржах")
ht = crypto.halving_table(ui.load)
c = st.columns([2, 3])
