# ---------- примеры ----------
def mvrv_window(start: str, end: str, text: str) -> None:
    w = o[start:end]
    c = st.columns(2)
    c[0].metric("MVRV: минимум / максимум", f"{w['mvrv'].min():.2f} / {w['mvrv'].max():.2f}", border=True)
    c[1].metric("Цена за период", f"{(w['price'].iloc[-1] / w['price'].iloc[0] - 1) * 100:+.0f}%", border=True)
    st.plotly_chart(dual_axis_chart(("Цена", w["price"], "$"), ("MVRV", w["mvrv"], "раз"), height=280),
                    width="stretch")
    st.markdown(text)


learn.examples([
    Example("2018–2019: держатели в убытке — дно", lambda: mvrv_window(
        "2018-06-01", "2019-07-01",
        "После пузыря 2017 года цена упала ниже средней цены покупки (MVRV меньше 1). Продали все, кто сдался; "
        "оставшиеся не продавали в убыток. Через несколько месяцев рынок развернулся.")),
    Example("2021: перегрев и фиксация прибыли", lambda: mvrv_window(
        "2020-10-01", "2022-01-01",
        "MVRV поднимался выше 3: держатели в огромной прибыли. Каждый рост встречал продажи долгосрочных "
        "держателей, и после двух вершин 2021 года начался медвежий рынок.")),
    Example("2024: халвинг без ракеты", lambda: mvrv_window(
        "2024-01-01", "2025-06-01",
        "Халвинг в апреле 2024 года прошёл почти незаметно: главным событием года были ETF, и вершина MVRV "
        "оказалась ниже прошлых. Выпуск новых монет перестал быть главным в цене."), normal=False),
], key="supply")

