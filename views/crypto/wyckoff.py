def range_chart(df: pd.DataFrame, m: pd.DataFrame, days: int = 240) -> go.Figure:
    w, mm = df.iloc[-days:], m.iloc[-days:]
    dark = theme() == "dark"
    fig = go.Figure()
    fig.add_trace(go.Scatter(x=w.index, y=w["c"], name="Закрытие", line=dict(width=2)))
    fig.add_trace(go.Scatter(x=w.index, y=mm["hi"], name="Верх диапазона 60 дн.", line=dict(width=1, dash="dot")))
    fig.add_trace(go.Scatter(x=w.index, y=mm["lo"], name="Низ диапазона 60 дн.", line=dict(width=1, dash="dot")))
    for col, name, sym in (("spring", "Spring", "triangle-up"), ("upthrust", "Upthrust", "triangle-down")):
        pts = w[mm[col].fillna(False)]
        fig.add_trace(go.Scatter(x=pts.index, y=pts["c"], mode="markers", name=name, marker=dict(size=11, symbol=sym)))
    fig.add_trace(go.Bar(x=w.index, y=w["v"] / 1e9, name="Оборот, млрд $", yaxis="y2", opacity=0.3))
    fig.update_layout(height=380, margin=dict(l=10, r=10, t=10, b=10), legend=dict(orientation="h", y=-0.15),
                      yaxis=dict(title="$"), yaxis2=dict(overlaying="y", side="right", showgrid=False,
                                                         title="млрд $"),
                      paper_bgcolor="rgba(0,0,0,0)", plot_bgcolor="rgba(0,0,0,0)",
                      font=dict(color="#ddd" if dark else "#333"))
    return fig


