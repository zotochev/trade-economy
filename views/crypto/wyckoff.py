days = st.segmented_control("Горизонт", [30, 90], default=30, key="wy_days", format_func=lambda d: f"{d} дней") or 30
t = crypto.wyckoff_test(ui.load, coin, days)
st.dataframe(t.style.format({"Случаев": "{:.0f}", t.columns[1]: "{:+.1f}", "Цена выше, %": "{:.0f}"}), width="stretch")
st.caption("Границы диапазона — минимум и максимум за 60 прошлых дней; соседние сигналы в пределах 20 дней — один "
           "случай. Сравнивайте с последней строкой: преимущество есть, только если результат заметно лучше обычного "
           "дня. Случаев немного — разница в 10 п.п. ещё может быть случайной.")
rg = crypto.ranges(ui.load, coin)
corr = float(rg["Дней в диапазоне"].rank().corr(rg["Ход за 90 дней после, %"].rank()))
st.markdown(f"**Причина и следствие.** Боковиков (размах до 30%, от 30 дней) с 2017 года: {len(rg)}. Связь длины "
            f"боковика с размером движения после него {corr:+.2f} (ранговая корреляция): "
            + ("её нет — долгий боковик не обещает большого движения." if abs(corr) < 0.2 else
               "она есть." if corr > 0 else "обратная."))

