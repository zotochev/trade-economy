with learn.how_it_works():
    st.markdown(f"""
- **Расстояние до ликвидации ≈ 100% / плечо.** При 10x — около 10%, при 50x — около 2%. Чуть меньше из-за
  поддерживающей маржи (~{crypto.MMR}% позиции), которую биржа оставляет себе как подушку.
- **Ликвидация срабатывает по «марк-цене»** — индексу цены на нескольких спотовых биржах со сглаженной поправкой.
  Это защищает от случайного выброса на одной бирже, но не от настоящего обвала.
- **Кросс-маржа включена на Binance по умолчанию.** В изолированной марже вы рискуете только залогом позиции. В
  кросс-марже в залог идёт весь счёт: реальное плечо — позиция, делённая на весь счёт, а не цифра на ползунке.
  Позиция живёт дольше, но если ликвидация придёт, она заберёт всё, и убыточные позиции по разным монетам тянут
  друг друга.
- **Стоп-лосс — не ликвидация.** Стоп вы ставите сами, и он срабатывает по цене последней сделки; в каскаде — с
  проскальзыванием, хуже заявленной цены. Правило трейдеров: стоп заметно раньше цены ликвидации, а размер позиции
  считают от расстояния до стопа (сколько готовы потерять), а не от плеча. Подробнее — в блоке 9.
- **Страховой фонд и ADL.** Если ликвидированная позиция закрылась хуже нуля, убыток покрывает страховой фонд биржи.
  Если фонда не хватает, биржа включает ADL — принудительно закрывает **прибыльные** позиции другой стороны. Даже
  выигрышную позицию или хедж могут закрыть без спроса (так было 10.10.2025).
- **Комиссии.** Около 0,05% от позиции за сделку по рынку: при 10x вход и выход съедают около 1% залога.
- **Волатильность важнее направления.** За месяц биткоин уходил против лонга на {crypto.liq_distance(10):.1f}% и больше в
  {odds.loc['10x', 'за месяц']:.0f}% случаев. Даже если вы угадали направление, с высоким плечом вас могут выбить по
  дороге.
- **Фандинг — плата за удержание.** В бессрочном фьючерсе нет даты погашения. Чтобы его цена не уходила от спота,
  каждые 8 часов (у многих альткоинов — каждые 4 или даже каждый час) одна сторона платит другой. Обычно лонги
  платят шортам: с 2019 года в среднем {cost_avg:.0f}% годовых от размера позиции. С плечом это умножается.
- **Альткоины опаснее.** Поддерживающая маржа у них выше (1–2,5% и растёт с размером позиции), колебания в разы
  больше, стакан тоньше — та же цифра плеча там значит гораздо больший риск.
""")

