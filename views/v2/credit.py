def ex_before():
    rows = []
    for a, _ in rec:
        if a.year < 1974:
            continue
        w = prob[(prob.index >= a - pd.DateOffset(months=12)) & (prob.index < a)]
        rows.append({"Рецессия началась": f"{a:%m.%Y}", "Максимум вероятности за год до, %": round(w.max())})
    table = pd.DataFrame(rows)
    st.dataframe(table, hide_index=True, width="stretch")
    typical, high = prob.median(), prob.quantile(0.75)
    col = "Максимум вероятности за год до, %"
    hit = int((table[col] > high).sum())
    st.markdown(
        f"Обычный уровень — около **{typical:.0f}%**. Перед {hit} из {len(table)} рецессий вероятность "
        f"поднималась выше {high:.0f}% — уровня, который бывает лишь в четверти месяцев. Исключение — 2020 год: "
        f"пандемия пришла извне, и кредитный рынок не мог её предвидеть.  \n"
        f"Смотрите и на ложные тревоги на графике выше: в 2011 и 2015–2016 годах вероятность тоже росла, "
        f"а рецессии не было. Хороший сигнал — не тот, что никогда не ошибается, а тот, чьи ошибки известны.")


