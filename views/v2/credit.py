def ex_lags():
    lags = sloos_lags()
    best = int(lags.idxmin())
    t = pd.DataFrame({"Корреляция": lags.values}, index=[f"+{k} кв." for k in lags.index])
    st.plotly_chart(grouped_bars(t, height=280), width="stretch")
    st.markdown(
        f"Сравниваем долю ужесточающих банков **сейчас** с ростом кредитов через 0, 1, … 8 кварталов. "
        f"Связь сильнее всего через **{best} кв.** (≈ {best * 3} мес.): корреляция {lags.min():.2f}. "
        f"Минус значит: банки ужесточили → кредиты затормозили. В тот же квартал связи почти нет "
        f"({lags.iloc[0]:+.2f}) — механизм работает **с задержкой**, и именно поэтому опрос полезен как "
        f"опережающий сигнал.")


