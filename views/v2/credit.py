def ex_gar():
    t, edges = growth_at_risk()
    now = float(nfci.resample("QS").mean().iloc[-1])
    bucket = BUCKETS[min(sum(now > e for e in edges[1:-1]), 4)]
    st.markdown(
        "Возьмём каждый квартал с 1971 года, разложим по пяти корзинам — от самых мягких финансовых условий "
        "до самых жёстких — и посмотрим, как росла экономика **в следующий год**.")
    st.plotly_chart(grouped_bars(t, units="%"), width="stretch")
    soft, hard = t.iloc[0], t.iloc[-1]
    st.markdown(
        f"**Что видно.** Типичный год отличается не так сильно: {soft.iloc[0]:+.1f}% при самых мягких условиях "
        f"против {hard.iloc[0]:+.1f}% при самых жёстких. А вот **плохой год** — совсем другой: "
        f"{soft.iloc[1]:+.1f}% против {hard.iloc[1]:+.1f}%. Жёсткие условия не столько замедляют экономику, "
        f"сколько **открывают дверь к спаду**. Это идея Growth-at-Risk (МВФ, ФРС): финансы двигают прежде всего "
        f"хвост риска.  \nСейчас мы в корзине «**{bucket.lower()}**».")


