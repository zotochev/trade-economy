FCIG_PARTS = {"FCIG_FFR": "Ставка ФРС", "FCIG_10Y": "10-летние", "FCIG_MORT": "Ипотека",
              "FCIG_BBB": "Облигации BBB", "FCIG_STOCK": "Акции", "FCIG_HOUSE": "Цены жилья",
              "FCIG_USD": "Доллар"}
BUCKETS = ["Самые мягкие", "Мягкие", "Средние", "Жёсткие", "Самые жёсткие"]


@st.cache_data(ttl=3600)
def impulse() -> tuple[pd.Series, pd.DataFrame]:
    """Вклад финансовых условий в рост ВВП, п.п. В FCI-G «плюс» = торможение; переворачиваем знак,
    чтобы на экране «плюс» означал помощь росту."""
    total = -ui.load("FCIG")
    parts = pd.DataFrame({name: -ui.load(k) for k, name in FCIG_PARTS.items()})
    return total, parts


@st.cache_data(ttl=3600)
def growth_at_risk() -> tuple[pd.DataFrame, list[float]]:
    """Рост ВВП за следующий год в зависимости от финансовых условий (NFCI) в начале этого года."""
    gdp = ui.load("GDPC1")
    fwd = (gdp.shift(-4) / gdp - 1) * 100
    nfci = ui.load("NFCI").resample("QS").mean()
    df = pd.concat({"nfci": nfci, "fwd": fwd}, axis=1, sort=True).dropna()
    df["bucket"], edges = pd.qcut(df["nfci"], 5, labels=BUCKETS, retbins=True)
    t = df.groupby("bucket", observed=True)["fwd"].agg(
        **{"Типичный год (медиана)": "median", "Плохой год (худшие 10%)": lambda x: x.quantile(0.1)})
    return t, list(edges)


@st.cache_data(ttl=3600)
def sloos_lags() -> pd.Series:
    """Корреляция «банки ужесточают сейчас» ↔ «рост кредитов через k кварталов»."""
    sloos = ui.load("DRTSCILM")
    loans = yoy_pct(ui.load("BUSLOANS")).resample("QS").mean()
    return pd.Series({k: sloos.corr(loans.shift(-k)) for k in range(0, 9)})


def ago(s: pd.Series, months: int) -> float:
    return float(s[:s.index[-1] - pd.DateOffset(months=months)].iloc[-1])


