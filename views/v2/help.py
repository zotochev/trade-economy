st.page_link("views/v2/map.py", label="Открыть карту", icon="🗺️")

st.header("Как читать экран слоя")
st.markdown("""
Каждый экран устроен одинаково — от главного к деталям. Можно остановиться на любом уровне.

1. **Строка цепочки вверху** — где этот слой в общей картине.
2. **Главный вывод в рамке** — ответ слоя по свежим данным одной фразой. Цвет кружка: 🟢 помогает росту /
   спокойно, 🔴 тормозит / тревожно, 🟠 стоит присмотреться, ⚪ нейтрально.
3. **Ключевые числа** — под каждым маленькая подсказка ⓘ (наведите курсор): что это и откуда.
4. **Разделы** — по одному механизму. В каждом: пара фраз, метки сигнала и график.
5. **💡 Как это работает** — раскрывается по клику: механизм, задержки, слабые места.
6. **📊 Показать на реальных данных** — переключатель с примерами. Сначала — *как механизм работает обычно*
   (цифры посчитаны из данных), затем — *когда он ломается* (кризисы и аномалии).
7. **Куда дальше по цепочке** — ссылки на следующие слои.

**На графиках:** серые полосы — официальные рецессии; наведите курсор — увидите значения всех линий на дату;
период графиков переключается над первым разделом.
""")

st.header("Метки сигналов")
st.markdown("""
| Метка | Что значит |
|---|---|
| :blue-badge[опережающий] | меняется **раньше** экономики — полезен для предупреждения |
| :violet-badge[совпадающий] | меняется **вместе** с экономикой — показывает, где мы сейчас |
| :gray-badge[запаздывающий] | меняется **позже** — подтверждает то, что уже случилось |
| :green-badge[проверен вне выборки] | работал на данных, которых не видели авторы модели — самая сильная проверка |
| :green-badge[проверен на истории] | связь видна в прошлых данных, но строгого теста вне выборки нет |
| :orange-badge[спорный] | исследования расходятся, или оценка сильно неточна |
| :red-badge[нарратив] | популярная история без строгой проверки — относиться осторожно |

Хороший сигнал — не тот, что никогда не ошибается, а тот, чьи ошибки известны. Поэтому в примерах всегда
есть раздел «когда он ломается».
""")

st.header("Как учиться с дашбордом")
st.markdown("""
- **Начните с карты.** Прочитайте ответы слоёв сверху вниз и найдите, где сейчас «напряжение» — какой слой
  тормозит, какой помогает.
- **Идите по цепочке, а не по списку.** Открыли политику ФРС → посмотрите, дошёл ли импульс до финансовых
  условий → до роста.
- **Сначала угадайте, потом проверьте.** Прежде чем открыть пример, предположите, что покажет график.
  Расхождение с вашим ожиданием — самое ценное место для обучения.
- **Возвращайтесь раз в месяц.** Данные обновляются; смотрите, как меняются ответы слоёв и совпадает ли это
  с вашими ожиданиями месяц назад.
""")

st.header("Глоссарий")
q = st.text_input("Поиск по терминам", placeholder="например, ставка или спред", key="glossary_q").strip().lower()
for term, (text, num) in sorted(GLOSSARY.items()):
    if q and q not in term.lower() and q not in text.lower():
        continue
    where = f" · :gray[слой {num}. {learn.BY_NUM[num].title}]" if num else ""
    st.markdown(f"**{term}** — {text}{where}")

