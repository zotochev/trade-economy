c[4].metric("Рынок ждёт", "повышения" if market > 0.25 else "снижения" if market < -0.25 else "паузы",
            f"2-летние − ставка: {market:+.2f}", delta_color="off", border=True,
            help="Доходность 2-летних облигаций против текущей ставки: выше — рынок ждёт роста ставки.")

years = PERIODS[st.segmented_control("Период графиков", list(PERIODS), default="20 лет", key="period")
                or "20 лет"]

# ---------- 1. тормоз или газ ----------
st.header("1. Тормоз или газ: реальная ставка против нейтральной")
