learn.examples([Example("Дорогие деньги → через полтора года растёт безработица", ex_unemployment),
                Example("2021: ставка у нуля при перегретой экономике", ex_2021, normal=False)], key="stance")

# ---------- 2. правила ----------
st.header("2. Что подсказывают правила")
st.markdown("Правило Тейлора — простая формула: где должна быть ставка при нынешних инфляции и безработице. "
            "ФРС ему не обязана следовать, но сама публикует такие правила как ориентир.")
learn.tags("совпадающий", "проверен на истории")
st.plotly_chart(band_chart({"Ставка ФРС": d["ffr"], "Правило Тейлора": d["taylor"],
                            "Сбалансированное правило": d["balanced"]},
                           (d["taylor"] - policy.RSTAR_BAND, d["taylor"] + policy.RSTAR_BAND,
                            "Правило Тейлора при r* ± 1 п.п."), recessions=rec), width="stretch")

with learn.how_it_works():
    st.markdown("""
**Формула словами:** ставка = нейтральная реальная ставка + инфляция
+ ½ × (инфляция − 2%) + 1 × (естественная безработица − безработица).

- **Инфляция выше цели** → ставку вверх, причём сильнее, чем выросла инфляция (иначе реальная ставка падает).
- **Безработица ниже естественной** (экономика перегрета) → ставку вверх.
- **Сбалансированное правило** вдвое сильнее реагирует на безработицу — его ФРС тоже публикует.
- **Ограничение:** правило не знает про шоки, финансовую стабильность и нижнюю границу ставки (ниже нуля
  ставку опустить почти нельзя). Поэтому это ориентир, а не инструкция.
""")


