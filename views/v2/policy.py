def ex_direction():
    ffr = ui.load("DFF").resample("MS").mean()
    spread = ui.load("DGS2").resample("MS").mean() - ffr
    fut = ffr.shift(-12) - ffr
    dd = pd.concat({"spread": spread, "fut": fut}, axis=1, sort=True).dropna()
    moved = dd[dd["fut"].abs() > 0.25]
    hit = ((moved["spread"] > 0) == (moved["fut"] > 0)).mean() * 100
    g = dd["2015":"2020"]
    st.plotly_chart(dual_axis_chart(("2-летние − ставка", g["spread"], "п.п."),
                                    ("Изменение ставки за следующий год", g["fut"], "п.п."), recessions=rec),
                    width="stretch")
    st.markdown(
        f"2015–2019: рынок ждал плавных повышений — и они пришли; в 2019 году 2-летние ушли ниже ставки, "
        f"и через несколько месяцев ФРС начала снижать. По всей истории с 1976 года, когда ставка за год "
        f"менялась больше чем на четверть пункта, знак этой разницы угадывал направление в **{hit:.0f}%** случаев.")


def ex_2022_market():
    g = pd.concat({"Ставка ФРС": ui.load("DFF")["2021-06":"2023-06"],
                   "2-летние облигации": ui.load("DGS2")["2021-06":"2023-06"]}, axis=1).ffill()
    st.plotly_chart(line_chart({k: g[k] for k in g}, units="%", recessions=rec, height=320), width="stretch")
    st.markdown(
        "В начале 2022 года 2-летние были около 0,8% — рынок ждал умеренных повышений. ФРС подняла ставку на "
        "4,25 п.п. за один год. Направление рынок угадал, масштаб — нет: он недооценил, насколько серьёзно "
        "ФРС настроена бороться с инфляцией. Ожидания хорошо ловят разворот, но плохо — величину.")


learn.examples([Example("Рынок угадывает направление ставки", ex_direction),
                Example("2022: направление угадали, масштаб — нет", ex_2022_market, normal=False)], key="market")

# ---------- 4. баланс ----------
st.header("4. Второй рычаг: баланс ФРС")
st.markdown("Когда ставку уже некуда снижать, ФРС покупает облигации за новые деньги — **QE**. Это сбивает "
            "длинные ставки и наполняет банки резервами. Обратный процесс — **QT**: ФРС даёт облигациям "
            "погаситься и изымает деньги.")
learn.tags("совпадающий", "спорный")
walcl = ui.load("WALCL") / 1e6
res = ui.load("WRESBAL") / 1e6
st.plotly_chart(line_chart({"Баланс ФРС, трлн $": cut(walcl, years), "Резервы банков, трлн $": cut(res, years)},
                           units="трлн $", recessions=rec, height=340), width="stretch")

with learn.how_it_works():
    st.markdown("""
- **Как QE действует.** ФРС выкупает длинные облигации → их меньше на рынке → цена растёт, доходность падает →
  дешевеют ипотека и корпоративные кредиты, инвесторы уходят в более рискованные активы.
- **Почему метка «спорный».** Величина эффекта QE до сих пор обсуждается: оценки разнятся в разы.
  Популярная «чистая ликвидность» (баланс − счёт Минфина − обратное РЕПО) хорошо совпадала с акциями в
  2020–2022 годах, но строгой проверки её предсказательной силы нет — это **нарратив**.
- **Как это связано со ставкой.** Исследование ФРБ Атланты (2026) предлагает смотреть на стойкость политики
  как на сумму двух рычагов: примерно ⅔ — ставка, ⅓ — баланс.
""")


def ex_qe():
    g = pd.concat({"Ставка ФРС": ui.load("DFF")["2007":"2016"],
                   "Баланс ФРС": (ui.load("WALCL") / 1e6)["2007":"2016"]}, axis=1).ffill()
    st.plotly_chart(dual_axis_chart(("Ставка ФРС", g["Ставка ФРС"], "%"),
                                    ("Баланс ФРС", g["Баланс ФРС"], "трлн $"), recessions=rec), width="stretch")
    st.markdown(
        f"В декабре 2008 года ставка упёрлась в ноль, и почти сразу начался QE: баланс вырос с ≈ 0,9 до "
        f"≈ {g['Баланс ФРС'].max():.1f} трлн $ к 2015 году. Когда первый рычаг исчерпан, ФРС берётся за второй — "
        f"это и есть нормальная логика баланса.")


learn.examples([Example("Ставка на нуле → включается QE", ex_qe)], key="balance")

