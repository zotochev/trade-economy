def ex_breadth():
    rows = {name: round(v, 2) for name, v in under.items()}
    t = pd.DataFrame({"Сейчас, % г/г": rows})
    st.plotly_chart(grouped_bars(t, units="%", height=260), width="stretch")
    robust = (under["Усечённая средняя PCE"] + under["Медианный CPI"]) / 2
    gap = under["Базовая PCE"] - robust
    if gap > 0.4:
        text = (f"Прямо сейчас меры расходятся: базовая PCE — **{under['Базовая PCE']:.1f}%**, а усечённая средняя "
                f"и медиана — около {robust:.1f}%. Значит, общий показатель тянут вверх несколько позиций, а "
                f"типичный товар или услуга дорожает медленнее. Такое расхождение обычно закрывается в пользу "
                f"устойчивых мер.")
    elif gap < -0.4:
        text = (f"Устойчивые меры (≈ {robust:.1f}%) выше обычной базовой PCE ({under['Базовая PCE']:.1f}%): "
                f"подорожание широкое, а базовую PCE временно сдерживают несколько подешевевших позиций.")
    else:
        text = (f"Меры согласны друг с другом (≈ {robust:.1f}–{under['Базовая PCE']:.1f}%): инфляция одинаково "
                f"широкая по всей корзине, без отдельных «выбросов».")
    st.markdown(text)


