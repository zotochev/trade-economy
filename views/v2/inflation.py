def ex_flat():
    u = ui.load("UNRATE")
    us = ui.load("NROU")[:u.index[-1]].resample("MS").ffill().reindex(u.index, method="ffill")
    d = pd.concat({"ug": us - u, "dp": core.shift(-12) - core}, axis=1, sort=True).dropna()
    rows = {}
    for name, a, z in [("1960–1989", "1960", "1989"), ("1990–2019", "1990", "2019")]:
        e = d[a:z]
        rows[name] = {"Ускорение инфляции на 1 п.п. перегрева": round(float(np.polyfit(e["ug"], e["dp"], 1)[0]), 2)}
    st.plotly_chart(grouped_bars(pd.DataFrame(rows).T, units=" п.п.", height=260), width="stretch")
    st.markdown(
        f"Насколько ускорялась базовая инфляция за следующий год, когда безработица была на 1 п.п. ниже "
        f"естественной. До 1990 года — заметно: перегрев разгонял цены. После — почти никак: кривая Филлипса "
        f"«уплощилась». В 2019 году безработица была {u['2019'].mean():.1f}% при естественной ≈ "
        f"{us['2019'].mean():.1f}%, а инфляция — лишь {core['2019'].mean():.1f}%. Главное объяснение — "
        f"заякоренные ожидания: люди перестали считать, что за перегревом обязательно последует инфляция.")


def ex_nonlinear():
    rows = {}
    for yr in ["2019", "2022", "2024"]:
        rows[yr] = {"Вакансий на безработного": round(vu[yr].mean(), 2), "Базовая PCE, %": round(core[yr].mean(), 1),
                    "Зарплаты, %": round(yoy("CES0500000003")[yr].mean(), 1)}
    st.plotly_chart(grouped_bars(pd.DataFrame(rows).T, height=300), width="stretch")
    st.markdown(
        f"В 2019 году вакансий на безработного было {rows['2019']['Вакансий на безработного']} — и инфляция "
        f"ниже цели. В 2022-м — {rows['2022']['Вакансий на безработного']}, и инфляция {rows['2022']['Базовая PCE, %']}%. "
        f"Сторонники нелинейной кривой Филлипса видят здесь подтверждение: выше порога связь резко усиливается. "
        f"Скептики возражают, что в 2022 году одновременно были сбой поставок, энергетический шок и огромные "
        f"бюджетные выплаты — отделить вклад рынка труда трудно. Вопрос открыт.")


