"""Слой 1. Структура и долг: потолок роста экономики, нейтральная ставка r* и арифметика госдолга (r − g)."""
import pandas as pd
import streamlit as st

from core import learn, structure, ui
from core.charts import grouped_bars, line_chart
from core.learn import Example
from core.transforms import cut, yoy_pct

PERIODS = {"20 лет": 20, "40 лет": 40, "Вся история": None}

# ---------- данные ----------
rec = ui.recessions()
pot = structure.potential_growth(ui.load)
hlw_g = ui.load("trend_g_hlw").dropna()
real_g = yoy_pct(ui.load("GDPC1")).dropna()
rs = structure.rstar(ui.load)
debt = structure.public_debt(ui.load)
r_avg = structure.debt_rate(ui.load)
g5 = structure.nominal_growth(ui.load)
head, color, x = structure.verdict(ui.load)

# ---------- шапка ----------
learn.layer_header(1, "Самый медленный слой: то, что меняется годами и задаёт рамки для всех остальных. "
                      "**Потолок роста** — сколько экономика может производить без перегрева. **Нейтральная "
                      "ставка r*** — точка отсчёта для ФРС (слой 2): «жёсткая» или «мягкая» политика меряется "
                      "от неё. **Госдолг** — во что обходится государству каждое повышение ставок.")

learn.takeaway(f"{head}. Средняя ставка по госдолгу {x.r_avg:.1f}%, по новым 10-летним займам {x.r_new:.1f}% — "
               f"против долгосрочного номинального роста ≈ {x.g:.1f}%. При первичном дефиците "
               f"{-x.primary:.1f}% ВВП долг растёт на ≈ {x.drift(x.r_avg):.1f} п.п. ВВП в год. Потолок реального "
               f"роста по CBO — {structure.cbo_outlook(ui.load):.1f}% в год.",
               {"orange": "warn", "red": "bad", "green": "good"}[color])

c = st.columns(5)
c[0].metric("Потолок роста (CBO)", f"{pot.iloc[-1]:.1f}%", f"прогноз на 10 лет: {structure.cbo_outlook(ui.load):.1f}%",
            delta_color="off", border=True, help="Рост потенциального ВВП: сколько экономика может прибавлять в год "
                                                 "при нормальной загрузке. Оценка бюджетного управления Конгресса.")
c[1].metric("Нейтральная ставка r*", f"{rs['Модель HLW (ФРБ Нью-Йорка)'].iloc[-1]:.1f}%",
            f"разброс оценок {min(v.iloc[-1] for v in rs.values()):.1f}–{max(v.iloc[-1] for v in rs.values()):.1f}%",
            delta_color="off", border=True, help="Реальная ставка, при которой экономика не перегревается и не "
                                                 "охлаждается. Модель HLW; разброс — три оценки из раздела 2.")
c[2].metric("Госдолг в руках публики", f"{x.d:.0f}% ВВП", f"{x.d - debt.iloc[-21]:+.0f} п.п. за 5 лет",
            delta_color="inverse", border=True, help="Долг государства инвесторам, банкам, ФРС и иностранцам.")
c[3].metric("Ставка по долгу − рост", f"{x.r_avg - x.g:+.1f} п.п.", f"по новым займам {x.r_new - x.g:+.1f}",
            delta_color="off", border=True, help="r − g. Минус — экономика растёт быстрее, чем копятся проценты.")
c[4].metric("Первичное сальдо бюджета", f"{x.primary:+.1f}% ВВП", "без процентов", delta_color="off", border=True,
            help="Доходы минус расходы государства без учёта процентов по долгу. Минус — дефицит.")

years = PERIODS[st.segmented_control("Период графиков", list(PERIODS), default="40 лет", key="period")
                or "40 лет"]

# ---------- 1. потолок роста ----------
st.header("1. Потолок роста")
st.markdown("Надолго экономика может расти только так быстро, как растут **число работников** и **выработка "
            "одного часа**. Быстрее — перегрев и инфляция (слой 6), медленнее — недогрузка и безработица (слой 5).")
learn.tags("запаздывающий", "проверен на истории")
st.plotly_chart(line_chart({"Потенциальный рост (CBO)": cut(pot, years), "Трендовый рост (HLW)": cut(hlw_g, years),
                            "Фактический рост ВВП, г/г": cut(real_g, years)}, units="%", recessions=rec,
                           zero_line=True, height=360), width="stretch")
with learn.how_it_works():
    st.markdown("""
- **Потолок = рост рабочей силы + рост производительности.** Рабочая сила растёт за счёт рождаемости,
  иммиграции и участия в труде; производительность — за счёт технологий, капитала и образования.
- **Его не видно напрямую.** CBO и модель HLW оценивают его по данным задним числом и пересматривают;
  ошибка — около полупроцента в год.
- **Зачем он остальным слоям.** Рост выше потолка разгоняет инфляцию; потолок вместе с инфляцией задаёт
  долгосрочный номинальный рост — то самое g в арифметике долга (раздел 3).
""")


def ex_eras():
    df = structure.sources(ui.load)
    st.plotly_chart(grouped_bars(df, units="%", height=300), width="stretch")
    st.markdown(
        f"Послевоенный бум держался на обоих моторах. В 1995–2004 годах компьютеры и интернет подняли "
        f"производительность до {df.loc['1995–2004', 'Производительность']:.1f}% в год, потом она вернулась к "
        f"{df.loc['2005–2019', 'Производительность']:.1f}%. А рабочая сила стареет: прирост упал с "
        f"{df.loc['1948–1973', 'Рабочая сила']:.1f}% до {df.loc['2020–н.в.', 'Рабочая сила']:.1f}% в год. "
        f"Поэтому потолок сейчас около 2%, а не 4%, как в 1960-х.")


def ex_2023():
    lf = yoy_pct(ui.load("CLF16OV").resample("QS").mean()).dropna()
    core = yoy_pct(ui.load("PCEPILFE")).dropna()
    rows = {y: {"Рост ВВП": real_g[y].mean(), "Потолок (CBO)": pot[y].mean(), "Рабочая сила": lf[y].mean(),
                "Базовая инфляция": core[y].mean()} for y in ["2019", "2023", "2024"]}
    st.plotly_chart(grouped_bars(pd.DataFrame(rows).T, units="%", height=300), width="stretch")
    st.markdown(
        f"В 2023–2024 годах экономика росла ≈ {real_g['2023':'2024'].mean():.1f}% в год — заметно выше "
        f"довоенного потолка ≈ {pot['2019'].mean():.1f}%, — а инфляция при этом падала. По учебнику так быть не "
        f"должно. Объяснение: сам потолок сдвинулся — иммиграция разогнала рабочую силу "
        f"({lf['2023'].mean():.1f}% в 2023 году против {lf['2019'].mean():.1f}% в 2019-м), подросла "
        f"производительность. CBO пересмотрела оценки вверх задним числом. Потолок — не константа.")


learn.examples([Example("Два мотора роста по эпохам", ex_eras),
                Example("2023–24: рост выше потолка без инфляции", ex_2023, normal=False)], key="supply")

# ---------- 2. r* ----------
st.header("2. Нейтральная ставка r*")
st.markdown("Реальная ставка, при которой экономика не разгоняется и не тормозит. Её нельзя наблюдать — только "
            "оценивать. Поэтому смотрим на **три оценки сразу**: модель, мнение ФРС и рынок облигаций.")
learn.tags("запаздывающий", "спорный")
st.plotly_chart(line_chart({k: cut(v, years) for k, v in rs.items()}, units="%", recessions=rec, zero_line=True,
                           height=340), width="stretch")
with learn.how_it_works():
    st.markdown("""
- **От чего зависит r*.** Много желающих сберегать (стареющее население, богатые страны Азии) и мало
  выгодных инвестиций — r* низкая. Быстрый рост производительности и большие дефициты бюджета — выше.
- **Три оценки — три взгляда.** Модель HLW выводит r* из того, ускоряется ли инфляция при данной ставке.
  Прогноз ФРС — мнение членов комитета. Рынок — какую реальную ставку инвесторы ждут через 5–10 лет
  (в ней ещё сидит премия за срок, слой 3).
- **Почему «спорный».** Ошибка модели HLW — около ±1 п.п., то есть порядка самой величины. Поэтому слой 2
  сравнивает ставку ФРС с r* только вместе с другими признаками.
""")


def ex_decline():
    h = rs["Модель HLW (ФРБ Нью-Йорка)"]
    st.markdown(
        f"По модели HLW r* снижалась сорок лет: {h['1990'].mean():.1f}% в 1990 году, {h['2007'].mean():.1f}% "
        f"перед кризисом 2008-го, {h['2019'].mean():.1f}% в 2019-м. Главные объяснения — старение населения "
        f"(больше сбережений на пенсию), медленный рост производительности, спрос всего мира на надёжные "
        f"американские облигации. Поэтому ставки ФРС в 2010-х и упирались в ноль: чтобы стимулировать "
        f"экономику, реальную ставку надо было опустить ниже нуля.")


def ex_split():
    now = {k: float(v.iloc[-1]) for k, v in rs.items()}
    then = {k: float(v["2019"].mean()) for k, v in rs.items()}
    st.plotly_chart(grouped_bars(pd.DataFrame({"2019 год": then, "Сейчас": now}), units="%", height=300),
                    width="stretch")
    fwd = "Рынок: реальная ставка через 5 лет на 5 лет"
    st.markdown(
        f"В 2019 году оценки почти совпадали. Сейчас рынок закладывает реальную ставку {now[fwd]:.1f}% — втрое "
        f"выше модели и ФРС. Либо рынок видит то, чего модели ещё не заметили (большие дефициты, инвестиции в "
        f"ИИ, деглобализация подняли r*), либо в его цене просто выросла премия за риск держать длинные "
        f"облигации. Ответ станет ясен только через годы — пока это главная неопределённость для слоя 2.")


learn.examples([Example("40 лет снижения r*", ex_decline),
                Example("После 2022: оценки разошлись", ex_split, normal=False)], key="rstar")

# ---------- 3. госдолг ----------
st.header("3. Госдолг: ставка против роста")
st.markdown("Долг страшен не сам по себе, а в сравнении двух чисел: **r** — средняя ставка, под которую занято, "
            "и **g** — номинальный рост экономики. Если r < g, доход страны растёт быстрее, чем копятся проценты.")
learn.tags("запаздывающий", "проверен на истории")
st.plotly_chart(line_chart({"Средняя ставка по госдолгу (r)": cut(r_avg, years),
                            "Рост номинального ВВП, среднее за 5 лет (g)": cut(g5, years),
                            "Ставка по новым 10-летним займам": cut(ui.load("DGS10").resample("MS").mean(), years)},
                           units="%", recessions=rec, height=340), width="stretch")
st.plotly_chart(line_chart({"Госдолг в руках публики, % ВВП": cut(debt, years)}, recessions=rec, height=240),
                width="stretch")
with learn.how_it_works():
    st.markdown("""
- **Формула.** За год долг к ВВП меняется на (r − g) × долг + первичный дефицит. Первичный — дефицит без
  процентов: то, что государство тратит сверх доходов на всё остальное.
- **Средняя ставка догоняет рыночную медленно.** Долг рефинансируется частями: при среднем сроке около
  шести лет повышение ставок ФРС доходит до бюджета за несколько лет. Поэтому смотрим и на ставку по
  новым займам.
- **Связь с цепочкой.** Высокая ставка ФРС (слой 2) удорожает долг; большие займы Минфина давят на премию
  за срок (слой 3). Это медленная обратная связь, а не повод для паники в любой год.
""")


def ex_70s():
    bal = ui.load("FYFSGDA188S")
    st.markdown(
        f"В 1970-х бюджет почти всегда был в дефиците (в среднем "
        f"{-bal['1970':'1979'].mean():.1f}% ВВП), но долг в руках публики держался около "
        f"{debt['1974'].mean():.0f}% ВВП: инфляция и рост держали g ≈ {g5['1979'].mean():.0f}%, выше ставки по "
        f"долгу ({r_avg['1979'].mean():.1f}%). Так же — ещё сильнее — США «перерастали» военный долг в 1946–1974 "
        f"годах. После 1980-го Волкер поднял ставки, r стала выше g, и долг почти удвоился к 1995 году "
        f"({debt['1995'].mean():.0f}% ВВП). Дефициты тоже выросли — в среднем "
        f"{-bal['1981':'1995'].mean():.1f}% ВВП против {-bal['1970':'1979'].mean():.1f}% в 1970-х, — но "
        f"половину работы сделала смена знака r − g.")


def ex_sandbox():
    st.markdown("Подвигайте ставку, рост и первичное сальдо — как изменится долг за 10 лет. Начальные значения — "
                "сегодняшние.")
    a, b, c_ = st.columns(3)
    r = a.slider("Средняя ставка по долгу r, %", 0.0, 8.0, round(x.r_avg, 1), 0.1, key="sb_r")
    g = b.slider("Номинальный рост g, %", 0.0, 8.0, round(x.g, 1), 0.1, key="sb_g")
    p = c_.slider("Первичное сальдо, % ВВП", -6.0, 4.0, round(x.primary, 1), 0.1, key="sb_p")
    idx = pd.date_range(debt.index[-1], periods=11, freq="YS")
    lines = {"Ваш сценарий": pd.Series(structure.path(x.d, r, g, p), index=idx),
             "Все долги под нынешнюю 10-летнюю ставку": pd.Series(structure.path(x.d, x.r_new, x.g, x.primary),
                                                                   index=idx)}
    st.plotly_chart(line_chart(lines, units="% ВВП", height=300), width="stretch")
    st.markdown(f"Чтобы долг перестал расти при r = {r:.1f}% и g = {g:.1f}%, нужно первичное сальдо "
                f"**{(r - g) / (100 + g) * x.d:+.1f}% ВВП**. Сейчас оно {x.primary:+.1f}%.")


learn.examples([Example("1970-е: долг таял при дефиците — r < g", ex_70s),
                Example("Песочница: долг через 10 лет", ex_sandbox)], key="debt")

