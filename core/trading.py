def diagnose(answers: list[str]) -> dict[str, int]:
    score = {k: 0 for k in PROFILES}
    for (_, opts), a in zip(QUESTIONS, answers):
        for k, v in opts.get(a, {}).items():
            score[k] += v
    return score
