"""Торговля: целевая функция трейдера — профили и моделирование кривых капитала."""
from dataclasses import dataclass

import numpy as np
import pandas as pd


def kelly(p_win: float, rr: float) -> float:
    """Доля счёта под риск по Келли: f* = p − (1 − p) / R. Ноль и меньше — edge нет, ставка ноль."""
    return max(p_win - (1 - p_win) / rr, 0.0)


def with_cost(rr: float, cost: float) -> float:
    """Трение (комиссия + проскальзывание, в R) уменьшает выигрыш и увеличивает проигрыш: R на единицу полного убытка."""
    return (rr - cost) / (1 + cost)


def fmt_pct(x: float) -> str:
    """Процент к старту; огромные — во сколько раз вырос счёт."""
    return f"×{1 + x / 100:,.0f}".replace(",", " ") if x > 1000 else f"{x:+.0f}%"


def simulate(p_win: float, rr: float, risk: float, trades: int, sims: int = 2000, seed: int = 0) -> np.ndarray:
    """Кривые капитала (sims × trades+1), старт 1. Удача — +rr·risk, неудача — −risk от текущего счёта."""
    rng = np.random.default_rng(seed)
    win = rng.random((sims, trades)) < p_win
    step = np.where(win, 1 + rr * risk, 1 - risk)
    return np.hstack([np.ones((sims, 1)), np.cumprod(step, axis=1)])


def stats(eq: np.ndarray, per_month: float) -> dict:
    """Итог, просадки и самое долгое время под водой (в месяцах) по пучку кривых."""
    peak = np.maximum.accumulate(eq, axis=1)
    dd = 1 - eq / peak
    under = eq < peak
    longest = np.zeros(len(eq), dtype=int)
    run = np.zeros(len(eq), dtype=int)
    for j in range(eq.shape[1]):
        run = np.where(under[:, j], run + 1, 0)
        longest = np.maximum(longest, run)
    final = (eq[:, -1] - 1) * 100
    mdd = dd.max(axis=1) * 100
    return {"Итог за период, медиана, %": float(np.median(final)),
            "Итог, худшие 5%, %": float(np.percentile(final, 5)),
            "Макс. просадка, медиана, %": float(np.median(mdd)),
            "Макс. просадка, худшие 5%, %": float(np.percentile(mdd, 95)),
            "Под водой подряд, медиана, мес": float(np.median(longest) / per_month),
            "Шанс просадки больше 30%, %": float((mdd > 30).mean() * 100)}


def bands(eq: np.ndarray, per_month: float) -> pd.DataFrame:
    """Медиана и коридор 5–95% кривой капитала по месяцам, % к старту."""
    idx = np.arange(eq.shape[1]) / per_month
    q = np.percentile((eq - 1) * 100, [5, 50, 95], axis=0)
    return pd.DataFrame({"Худшие 5%": q[0], "Медиана": q[1], "Лучшие 5%": q[2]}, index=idx)


